import { describe, expect, it } from 'vitest'
import { createDoiClient, interpretDoiRa } from '../src/clients/doi.js'
import { createOpenAlexClient, mapOpenAlexWork } from '../src/clients/openalex.js'
import { RetrievalCache } from '../src/lib/cache.js'
import { ServiceUnavailableError } from '../src/lib/http.js'
import { Scheduler } from '../src/lib/scheduler.js'
import { fixtureJson, fixtureText, ok, status, stubFetch, testHttp } from './helpers.js'

const instant = () => new Scheduler({ maxConcurrent: 5, minIntervalMs: 0 })

describe('OpenAlex client', () => {
  it('maps a recorded work', () => {
    const w = fixtureJson<{ results: unknown[] }>('openalex-search-walters.json').results[0]
    expect(mapOpenAlexWork(w)).toEqual({
      source: 'openalex',
      doi: '10.1038/s41598-023-41032-5',
      url: 'https://doi.org/10.1038/s41598-023-41032-5',
      title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
      authors: ['Walters', 'Wilder'],
      authorsFull: ['William H. Walters', 'Esther Isabelle Wilder'],
      year: 2023,
      venue: 'Scientific Reports',
      volume: '13',
      issue: '1',
      pages: '14045',
    })
  })

  it('builds a page range and falls back to the landing page when there is no DOI', () => {
    const r = mapOpenAlexWork({
      id: 'https://openalex.org/W1',
      title: 'T',
      doi: null,
      biblio: { first_page: '10', last_page: '20' },
      primary_location: { landing_page_url: 'https://example.org/paper', source: null },
    })
    expect(r).toMatchObject({
      doi: null,
      url: 'https://example.org/paper',
      pages: '10-20',
      venue: null,
    })
  })

  it('returns null without a title', () => {
    expect(mapOpenAlexWork({ id: 'x' })).toBeNull()
  })

  it('searches by title with search.title, five results, and no key by default', async () => {
    const { fetchImpl, calls } = stubFetch([
      { match: () => true, respond: () => ok(fixtureText('openalex-search-walters.json')) },
    ])
    const client = createOpenAlexClient({
      http: testHttp(fetchImpl),
      cache: new RetrievalCache(),
      scheduler: instant(),
    })
    const found = await client.searchTitle('Fabrication, and errors: a title with a comma')
    expect(found).toHaveLength(1)
    const url = new URL(calls[0]?.url as string)
    expect(url.searchParams.get('search.title')).toBe(
      'Fabrication, and errors: a title with a comma',
    )
    expect(url.searchParams.get('per_page')).toBe('5')
    expect(url.searchParams.has('api_key')).toBe(false)
    expect((calls[0]?.init?.headers as Record<string, string>).authorization).toBeUndefined()
  })

  it('sends the API key as a bearer token, never in the URL', async () => {
    const { fetchImpl, calls } = stubFetch([
      { match: () => true, respond: () => ok({ results: [] }) },
    ])
    const client = createOpenAlexClient({
      http: testHttp(fetchImpl),
      apiKey: 'secret-key',
      scheduler: instant(),
    })
    await client.searchTitle('x')
    expect(calls[0]?.url).not.toContain('secret-key')
    expect((calls[0]?.init?.headers as Record<string, string>).authorization).toBe(
      'Bearer secret-key',
    )
  })

  it('returns an empty list for no results and caches it', async () => {
    const { fetchImpl, calls } = stubFetch([
      { match: () => true, respond: () => ok(fixtureText('openalex-search-nomatch.json')) },
    ])
    const client = createOpenAlexClient({ http: testHttp(fetchImpl), scheduler: instant() })
    expect(await client.searchTitle('Nothing')).toEqual([])
    expect(await client.searchTitle('nothing')).toEqual([])
    expect(calls).toHaveLength(1)
  })

  it('fails fast when the free budget is used up (429 with a long Retry-After)', async () => {
    const { fetchImpl, calls } = stubFetch([
      { match: () => true, respond: () => status(429, '', { 'retry-after': '40000' }) },
    ])
    const client = createOpenAlexClient({ http: testHttp(fetchImpl), scheduler: instant() })
    await expect(client.searchTitle('x')).rejects.toMatchObject({ code: 'rate_limited' })
    expect(calls).toHaveLength(1)
  })

  it('reports an inactive key (403) as unavailable, not as "no results"', async () => {
    const { fetchImpl } = stubFetch([
      {
        match: () => true,
        respond: () => status(403, JSON.stringify({ code: 'key_not_activated' })),
      },
    ])
    const client = createOpenAlexClient({
      http: testHttp(fetchImpl),
      apiKey: 'k',
      scheduler: instant(),
    })
    await expect(client.searchTitle('x')).rejects.toMatchObject({ code: 'blocked' })
  })

  it('reports a malformed body as a bad response', async () => {
    const { fetchImpl } = stubFetch([{ match: () => true, respond: () => ok({ meta: {} }) }])
    const client = createOpenAlexClient({ http: testHttp(fetchImpl), scheduler: instant() })
    await expect(client.searchTitle('x')).rejects.toMatchObject({ code: 'bad_response' })
  })
})

describe('doi.org registration agency client', () => {
  it('interprets the three recorded answers', () => {
    expect(interpretDoiRa(fixtureJson('doira-crossref.json'))).toEqual({
      kind: 'registered',
      agency: 'Crossref',
    })
    expect(interpretDoiRa(fixtureJson('doira-datacite.json'))).toEqual({
      kind: 'registered',
      agency: 'DataCite',
    })
    expect(interpretDoiRa(fixtureJson('doira-notfound.json'))).toEqual({ kind: 'not_registered' })
  })

  it('treats "Invalid DOI" as not registered', () => {
    expect(interpretDoiRa([{ DOI: 'x', status: 'Invalid DOI' }])).toEqual({
      kind: 'not_registered',
    })
  })

  it.each([[[{ DOI: 'x', status: 'Unknown' }]], [{}], [[]], [null], [[{ DOI: 'x' }]]])(
    'refuses to guess from %j',
    (body) => {
      expect(() => interpretDoiRa(body)).toThrow(ServiceUnavailableError)
    },
  )

  it('queries doiRA and caches the answer, including "not registered"', async () => {
    const { fetchImpl, calls } = stubFetch([
      { match: () => true, respond: () => ok(fixtureText('doira-notfound.json')) },
    ])
    const client = createDoiClient({ http: testHttp(fetchImpl), scheduler: instant() })
    expect(await client.getAgency('10.9999/this-doi-does-not-exist-12345')).toEqual({
      kind: 'not_registered',
    })
    expect(await client.getAgency('10.9999/THIS-DOI-DOES-NOT-EXIST-12345')).toEqual({
      kind: 'not_registered',
    })
    expect(calls).toHaveLength(1)
    expect(calls[0]?.url).toBe('https://doi.org/doiRA/10.9999/this-doi-does-not-exist-12345')
  })

  it('throws when doi.org is down, so the caller reports check_failed', async () => {
    const { fetchImpl } = stubFetch([
      { match: () => true, respond: () => status(500) },
      { match: () => true, respond: () => status(500) },
      { match: () => true, respond: () => status(500) },
    ])
    const client = createDoiClient({ http: testHttp(fetchImpl), scheduler: instant() })
    await expect(client.getAgency('10.1/x')).rejects.toBeInstanceOf(ServiceUnavailableError)
  })
})
