import type { MatchedRecord, ParsedReference } from '@cekkutip/shared'
import { describe, expect, it } from 'vitest'
import {
  authorScore,
  citedSurnameTokens,
  pickBest,
  scoreCandidate,
  venueSimilarity,
} from '../src/pipeline/match.js'

const rec = (over: Partial<MatchedRecord> = {}): MatchedRecord => ({
  source: 'crossref',
  doi: '10.1/x',
  url: null,
  title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
  authors: ['Walters', 'Wilder'],
  authorsFull: ['William H. Walters', 'Esther Isabelle Wilder'],
  year: 2023,
  venue: 'Scientific Reports',
  volume: '13',
  issue: '1',
  pages: '14045',
  ...over,
})

const ref = (over: Partial<ParsedReference> = {}): ParsedReference => ({
  raw: 'x',
  authors: ['Walters', 'Wilder'],
  hasEtAl: false,
  year: 2023,
  title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
  venue: 'Scientific Reports',
  volume: null,
  issue: null,
  pages: null,
  doi: null,
  type: 'journal_article',
  parseMode: 'llm',
  ...over,
})

describe('citedSurnameTokens', () => {
  it.each([
    ['Walters', ['walters']],
    ['Walters, W. H.', ['walters']],
    ['W. H. Walters', ['walters']],
    ['& Wilder', ['wilder']],
    ['and Wilder', ['wilder']],
    ['dan Wijaya', ['wijaya']],
    ['Müller', ['muller']],
    ['van der Berg', ['van', 'der', 'berg']],
    ["O'Brien", ['obrien']],
    ['J.', []],
  ])('%j gives %j', (input, tokens) => {
    expect(citedSurnameTokens(input)).toEqual(tokens)
  })
})

describe('authorScore', () => {
  it('is 1 when every cited family name is found', () => {
    expect(authorScore(ref(), rec())).toEqual({ score: 1, compared: 2 })
  })

  it('is the share found when some are missing', () => {
    expect(authorScore(ref({ authors: ['Walters', 'Smith'] }), rec()).score).toBe(0.5)
    expect(authorScore(ref({ authors: ['Smith', 'Jones', 'Walters'] }), rec()).score).toBeCloseTo(
      1 / 3,
    )
  })

  it('ignores case, diacritics, and the order of authors', () => {
    expect(authorScore(ref({ authors: ['WILDER', 'walters'] }), rec()).score).toBe(1)
    expect(
      authorScore(
        ref({ authors: ['Müller'] }),
        rec({ authors: ['Muller'], authorsFull: ['Hans Muller'] }),
      ).score,
    ).toBe(1)
  })

  it('handles "&" and "and" left on a name', () => {
    expect(authorScore(ref({ authors: ['Walters', '& Wilder'] }), rec()).score).toBe(1)
  })

  it('matches a single-name Indonesian author through the full name', () => {
    const r = rec({ authors: ['Santoso'], authorsFull: ['Budi Santoso'] })
    expect(authorScore(ref({ authors: ['Budi'] }), r).score).toBe(1)
    expect(authorScore(ref({ authors: ['Santoso'] }), r).score).toBe(1)
  })

  it('matches multi-word surnames, with OpenAlex-style last-word family names', () => {
    const openalex = rec({ authors: ['Berg'], authorsFull: ['Jan van der Berg'] })
    expect(authorScore(ref({ authors: ['van der Berg'] }), openalex).score).toBe(1)
    expect(authorScore(ref({ authors: ['Berg'] }), openalex).score).toBe(1)
  })

  it('does not match a different name that merely contains the same letters', () => {
    expect(authorScore(ref({ authors: ['Walter'] }), rec()).score).toBe(0)
  })

  it('with et al., compares only the written authors but needs the first one to match', () => {
    const many = rec({
      authors: ['Vaswani', 'Shazeer', 'Parmar', 'Uszkoreit'],
      authorsFull: ['Ashish Vaswani', 'Noam Shazeer', 'Niki Parmar', 'Jakob Uszkoreit'],
    })
    expect(authorScore(ref({ authors: ['Vaswani'], hasEtAl: true }), many).score).toBe(1)
    expect(authorScore(ref({ authors: ['Shazeer'], hasEtAl: true }), many).score).toBe(0) // not first
    expect(authorScore(ref({ authors: ['Vaswani', 'Smith'], hasEtAl: true }), many).score).toBe(0.5)
  })

  it('reports nothing compared when no authors were cited', () => {
    expect(authorScore(ref({ authors: [] }), rec())).toEqual({ score: 0, compared: 0 })
    expect(authorScore(ref({ authors: ['J.'] }), rec()).compared).toBe(0)
  })
})

describe('venueSimilarity', () => {
  it('is 1 for the same venue', () => {
    expect(venueSimilarity('Scientific Reports', 'Scientific Reports')).toBe(1)
  })

  it('ignores generic words such as "Journal of"', () => {
    expect(
      venueSimilarity('Journal of Chemical Physics', 'Chemical Physics'),
    ).toBeGreaterThanOrEqual(0.9)
    expect(venueSimilarity('Jurnal Pendidikan', 'Pendidikan')).toBeGreaterThanOrEqual(0.9)
  })

  it('accepts abbreviations', () => {
    expect(venueSimilarity('Sci. Rep.', 'Scientific Reports')).toBeGreaterThanOrEqual(0.9)
    expect(
      venueSimilarity('J. Pers. Soc. Psychol.', 'Journal of Personality and Social Psychology'),
    ).toBeGreaterThanOrEqual(0.9)
  })

  it('accepts acronyms', () => {
    expect(
      venueSimilarity('PNAS', 'Proceedings of the National Academy of Sciences'),
    ).toBeGreaterThanOrEqual(0.9)
    expect(
      venueSimilarity('JAMA', 'Journal of the American Medical Association'),
    ).toBeGreaterThanOrEqual(0.9)
  })

  it('is low for clearly different venues', () => {
    expect(venueSimilarity('Nature Communications', 'Scientific Reports')).toBeLessThan(0.4)
    expect(venueSimilarity('Journal of Chemistry', 'Journal of Physics')).toBeLessThan(0.5)
  })

  it('is lenient when one venue contains the other', () => {
    expect(venueSimilarity('Nature', 'Nature Communications')).toBeGreaterThanOrEqual(0.5)
  })

  it('is 0 when there is nothing to compare', () => {
    expect(venueSimilarity('', 'Scientific Reports')).toBe(0)
    expect(venueSimilarity('...', 'Scientific Reports')).toBe(0)
  })
})

describe('scoreCandidate', () => {
  const opts = { checkAuthors: true }

  it('scores a perfect match', () => {
    const s = scoreCandidate(ref(), rec(), opts)
    expect(s.scores).toEqual({ title: 1, authors: 1, yearDiff: 0, venue: 1 })
    expect(s.flags).toEqual({
      titleCited: true,
      authorsCited: true,
      yearCited: true,
      venueCompared: true,
    })
  })

  it('computes the year difference in either direction', () => {
    expect(scoreCandidate(ref({ year: 2021 }), rec(), opts).scores.yearDiff).toBe(2)
    expect(scoreCandidate(ref({ year: 2025 }), rec(), opts).scores.yearDiff).toBe(2)
  })

  it('leaves year difference null when either year is missing', () => {
    expect(scoreCandidate(ref({ year: null }), rec(), opts).scores.yearDiff).toBeNull()
    expect(scoreCandidate(ref(), rec({ year: null }), opts).scores.yearDiff).toBeNull()
  })

  it('marks uncited fields as not cited instead of scoring them as wrong', () => {
    const s = scoreCandidate(
      ref({ title: null, authors: [], venue: null, year: null }),
      rec(),
      opts,
    )
    expect(s.flags).toEqual({
      titleCited: false,
      authorsCited: false,
      yearCited: false,
      venueCompared: false,
    })
  })

  it('does not compare venues when the record has none', () => {
    expect(scoreCandidate(ref(), rec({ venue: null }), opts).flags.venueCompared).toBe(false)
  })

  it('A4: skips authors entirely', () => {
    const s = scoreCandidate(ref({ authors: ['Nobody'] }), rec(), { checkAuthors: false })
    expect(s.flags.authorsCited).toBe(false)
    expect(s.scores.authors).toBe(0)
  })

  it('uses the main title when the citation omits the subtitle', () => {
    const r = rec({ title: 'Attention is all you need: a long subtitle follows' })
    expect(scoreCandidate(ref({ title: 'Attention is all you need' }), r, opts).scores.title).toBe(
      1,
    )
  })
})

describe('pickBest', () => {
  const opts = { checkAuthors: true }

  it('returns null for no candidates', () => {
    expect(pickBest(ref(), [], opts)).toBeNull()
  })

  it('prefers the higher title score', () => {
    const good = rec({ doi: '10.1/good' })
    const worse = rec({
      doi: '10.1/worse',
      title: 'Fabrication and errors in citations from some chatbot',
    })
    expect(pickBest(ref(), [worse, good], opts)?.record.doi).toBe('10.1/good')
  })

  it('breaks a title tie by author score', () => {
    const wrongAuthors = rec({ doi: '10.1/a', authors: ['Smith'], authorsFull: ['Jo Smith'] })
    const rightAuthors = rec({ doi: '10.1/b' })
    expect(pickBest(ref(), [wrongAuthors, rightAuthors], opts)?.record.doi).toBe('10.1/b')
  })

  it('then prefers the smaller year difference (preprint versus published version)', () => {
    const preprint = rec({ doi: '10.1/pre', year: 2022 })
    const published = rec({ doi: '10.1/pub', year: 2023 })
    expect(pickBest(ref({ year: 2023 }), [preprint, published], opts)?.record.doi).toBe('10.1/pub')
  })

  it('keeps the service order when everything is equal', () => {
    const first = rec({ doi: '10.1/first' })
    const second = rec({ doi: '10.1/second' })
    expect(pickBest(ref(), [first, second], opts)?.record.doi).toBe('10.1/first')
  })
})
