/**
 * A person's own Gemini key: sent in a header, used for that request only, never stored, logged,
 * or echoed. When the model cannot be used, the response says why, as a code.
 */

const servers: Server[] = []
afterEach(async () => {
  await Promise.all(servers.splice(0).map((s) => new Promise((r) => s.close(r))))
})

const KEY = 'AIzaSyOwnKeyForTests-1234567890abcdefgh'

interface Opts {
  rules?: Rule[]
  limits?: Partial<Limits>
  logger?: AppLogger
  gemini?: GeminiClient
  createGemini?: (apiKey: string) => GeminiClient
}

async function start(o: Opts = {}) {
  const w = world(o.rules ?? FIXTURE_RULES, o.gemini)
  const app = createApp({
    pipeline: w.deps,
    createGemini: o.createGemini,
    limits: { ...loadLimits({}), ...o.limits },
    env: loadEnv({ NODE_ENV: 'test' }),
    logger: o.logger ?? silentLogger,
  })
  const server = await new Promise<Server>((resolve) => {
    const s = app.listen(0, '127.0.0.1', () => resolve(s))
  })
  servers.push(server)
  return `http://127.0.0.1:${(server.address() as AddressInfo).port}`
}

const post = (base: string, body: unknown, key?: string) =>
  fetch(`${base}/api/check`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      ...(key === undefined ? {} : { 'x-gemini-key': key }),
    },
    body: typeof body === 'string' ? body : JSON.stringify(body),
  })

async function eventsOf(res: Response): Promise<StreamEvent[]> {
  return (await res.text())
    .split('\n')
    .filter((l) => l !== '')
    .map((l) => StreamEventSchema.parse(JSON.parse(l)))
}

async function doneOf(res: Response) {
  const list = await eventsOf(res)
  const done = list.find((e) => e.type === 'done')
  if (done?.type !== 'done') throw new Error('no done event')
  return { list, summary: done.summary }
}

const parseModes = (list: StreamEvent[]) =>
  list.flatMap((e) => (e.type === 'result' ? [e.result.parsed.parseMode] : []))

/** A model client that reads every reference as the Walters paper, and records the keys it was built with. */
function fakeFactory() {
  const keys: string[] = []
  const batches: string[][] = []
  const createGemini = (apiKey: string): GeminiClient => {
    keys.push(apiKey)
    return {
      extract: async (items) => {
        batches.push(items.map((i) => i.text))
        return {
          usage: { inputTokens: 0, outputTokens: 0 },
          results: items.map((it) => ({
            i: it.i,
            authors: ['Walters', 'Wilder'],
            hasEtAl: false,
            year: 2023,
            title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
            venue: 'Scientific Reports',
            volume: null,
            issue: null,
            pages: null,
            doi: null,
            type: 'journal_article',
          })),
        }
      },
    }
  }
  return { keys, batches, createGemini }
}

const failing =
  (code: ConstructorParameters<typeof ServiceUnavailableError>[1], http: number) =>
  (): GeminiClient => ({
    extract: async () => {
      throw new ServiceUnavailableError('gemini', code, http)
    },
  })

describe('reading with the key', () => {
  it("uses the person's key, even when the server has none of its own", async () => {
    const f = fakeFactory()
    const base = await start({ createGemini: f.createGemini })
    const { list, summary } = await doneOf(await post(base, { references: [REF_OK] }, KEY))
    expect(f.keys).toEqual([KEY])
    expect(f.batches).toHaveLength(1)
    expect(parseModes(list)).toEqual(['llm'])
    expect(summary.aiIssue).toBeNull()
  })

  it('builds the client for that request only: the next request without a key does not reuse it', async () => {
    const f = fakeFactory()
    const base = await start({ createGemini: f.createGemini })
    await (await post(base, { references: [REF_OK] }, KEY)).text()
    const { list } = await doneOf(await post(base, { references: [REF_OK] }))
    expect(f.keys).toHaveLength(1)
    expect(parseModes(list)).toEqual(['regex'])
  })

  it('prefers the key over the server reader when both exist', async () => {
    const shared = fakeFactory()
    const own = fakeFactory()
    const base = await start({
      gemini: shared.createGemini('server-key-not-the-persons-0123456789'),
      createGemini: own.createGemini,
    })
    await (await post(base, { references: [REF_OK] }, KEY)).text()
    expect(own.batches).toHaveLength(1)
    expect(shared.batches).toHaveLength(0)
  })

  it('cleans quotes and spaces pasted around the key', async () => {
    const f = fakeFactory()
    const base = await start({ createGemini: f.createGemini })
    await (await post(base, { references: [REF_OK] }, `  "${KEY}" `)).text()
    expect(f.keys).toEqual([KEY])
  })

  it('treats an empty header as no key', async () => {
    const f = fakeFactory()
    const base = await start({ createGemini: f.createGemini })
    const res = await post(base, { references: [REF_OK] }, '   ')
    expect(res.status).toBe(200)
    await res.text()
    expect(f.keys).toHaveLength(0)
  })
})

describe('a key that cannot be used', () => {
  it('is refused before streaming when it cannot be a key, without echoing it', async () => {
    const f = fakeFactory()
    const base = await start({ createGemini: f.createGemini })
    const bad = 'not a key at all'
    const res = await post(base, { references: [REF_OK] }, bad)
    expect(res.status).toBe(400)
    const body = (await res.json()) as { error: { code: string; message: string } }
    expect(body.error.code).toBe('invalid_api_key')
    expect(JSON.stringify(body)).not.toContain(bad)
    expect(f.keys).toHaveLength(0)
  })

  it('is refused, not ignored, when the server cannot build a client for it', async () => {
    const base = await start()
    const res = await post(base, { references: [REF_OK] }, KEY)
    expect(res.status).toBe(400)
    expect(((await res.json()) as { error: { code: string } }).error.code).toBe('invalid_api_key')
  })

  it('is reported as "rejected" when Google refuses it, and the check still finishes', async () => {
    const base = await start({ createGemini: failing('blocked', 400) })
    const { list, summary } = await doneOf(await post(base, { references: [REF_OK, THESIS] }, KEY))
    expect(summary.aiIssue).toBe('rejected')
    expect(parseModes(list)).toEqual(['regex', 'regex'])
    expect(summary.checkFailed).toBe(0) // a refused key is not a failed lookup
  })

  it('is reported as "quota" when its limit is reached', async () => {
    const base = await start({ createGemini: failing('rate_limited', 429) })
    const { summary } = await doneOf(await post(base, { references: [REF_OK] }, KEY))
    expect(summary.aiIssue).toBe('quota')
  })

  it('reports no issue when the model failed for another reason, or when no key was used', async () => {
    const base = await start({ createGemini: failing('server_error', 503) })
    expect(
      (await doneOf(await post(base, { references: [REF_OK] }, KEY))).summary.aiIssue,
    ).toBeNull()
    expect((await doneOf(await post(base, { references: [REF_OK] }))).summary.aiIssue).toBeNull()
  })

  it('reports the shared reader reaching its limit too, so the page can offer the person their own key', async () => {
    const base = await start({ gemini: failing('rate_limited', 429)() })
    const { summary } = await doneOf(await post(base, { references: [REF_OK] }))
    expect(summary.aiIssue).toBe('quota')
  })

  it('reports a refusal once even when several batches hit it, and a refusal wins over quota', async () => {
    let n = 0
    const createGemini = (): GeminiClient => ({
      extract: async () => {
        n += 1
        throw new ServiceUnavailableError('gemini', n === 1 ? 'rate_limited' : 'blocked', 400)
      },
    })
    const base = await start({ createGemini, limits: { parseBatchSize: 1 } })
    const { summary } = await doneOf(await post(base, { references: [REF_OK, THESIS] }, KEY))
    expect(summary.aiIssue).toBe('rejected')
  })
})

describe('the key is never written anywhere', () => {
  const capture = () => {
    const lines: string[] = []
    const destination = new Writable({
      write(chunk: Buffer, _enc, cb) {
        lines.push(chunk.toString())
        cb()
      },
    })
    return { lines, logger: createLogger({ level: 'debug', destination }) }
  }

  it('is absent from every log line, response, and error, on every path', async () => {
    const { lines, logger } = capture()
    const f = fakeFactory()
    const junk = 'AIza bad key with spaces'
    const down: Rule[] = [{ repeat: true, match: () => true, respond: () => status(503) }]
    const bodies: string[] = []

    const normal = await start({ logger, createGemini: f.createGemini })
    bodies.push(await (await post(normal, { references: [REF_OK] }, KEY)).text())
    const refused = await start({ logger, createGemini: failing('blocked', 400) })
    bodies.push(await (await post(refused, { references: [REF_OK] }, KEY)).text())
    const lookupsDown = await start({ logger, createGemini: f.createGemini, rules: down })
    bodies.push(await (await post(lookupsDown, { references: [REF_OK] }, KEY)).text())
    const tooMany = await start({
      logger,
      createGemini: f.createGemini,
      limits: { maxReferences: 1 },
    })
    bodies.push(await (await post(tooMany, { references: [REF_OK, REF_OK] }, KEY)).text())
    bodies.push(await (await post(normal, '{"references":', KEY)).text())
    bodies.push(await (await post(normal, { references: [REF_OK] }, junk)).text())

    const log = lines.join('')
    expect(log.length).toBeGreaterThan(0)
    expect(log).not.toContain(KEY)
    expect(log).not.toContain('OwnKeyForTests')
    expect(log).not.toContain(junk)
    for (const body of bodies) {
      expect(body).not.toContain(KEY)
      expect(body).not.toContain(junk)
    }
  })

  it('leaves only a flag in the log, true when a key was used', async () => {
    const { lines, logger } = capture()
    const f = fakeFactory()
    const base = await start({ logger, createGemini: f.createGemini })
    await (await post(base, { references: [REF_OK] }, KEY)).text()
    await (await post(base, { references: [REF_OK] })).text()
    const checks = lines
      .map((l) => JSON.parse(l) as Record<string, unknown>)
      .filter((e) => e.event === 'check')
    expect(checks.map((c) => c.ownKey)).toEqual([true, false])
  })
})
