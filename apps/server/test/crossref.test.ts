import { describe, expect, it } from 'vitest'
import { createCrossrefClient, mapCrossrefItem } from '../src/clients/crossref.js'
import { RetrievalCache } from '../src/lib/cache.js'
import { ServiceUnavailableError } from '../src/lib/http.js'
import { Scheduler } from '../src/lib/scheduler.js'
import { fixtureJson, fixtureText, ok, status, stubFetch, testHttp, urlHas } from './helpers.js'

const DOI = '10.1038/s41598-023-41032-5'
const WALTERS = 'Fabrication and errors in the bibliographic citations generated by ChatGPT'

function setup(rules: Parameters<typeof stubFetch>[0], mailto?: string) {
  const { fetchImpl, calls } = stubFetch(rules)
  const client = createCrossrefClient({
    http: testHttp(fetchImpl),
    mailto,
    cache: new RetrievalCache(),
    scheduler: new Scheduler({ maxConcurrent: 5, minIntervalMs: 0 }),
  })
  return { client, calls }
}

describe('mapCrossrefItem', () => {
  it('maps a recorded work', () => {
    const message = fixtureJson<{ message: unknown }>('crossref-work-walters.json').message
    expect(mapCrossrefItem(message)).toEqual({
      source: 'crossref',
      doi: DOI,
      url: `https://doi.org/${DOI}`,
      title: WALTERS,
      authors: ['Walters', 'Wilder'],
      authorsFull: ['William H. Walters', 'Esther Isabelle Wilder'],
      year: 2023,
      venue: 'Scientific Reports',
      volume: '13',
      issue: '1',
      pages: '14045', // from article-number: this work has no page range
    })
  })

  it('merges a subtitle into the title once', () => {
    const base = { DOI: '10.1/x', title: ['Main title'], subtitle: ['The subtitle'] }
    expect(mapCrossrefItem(base)?.title).toBe('Main title: The subtitle')
    const dup = { DOI: '10.1/x', title: ['Main title: The subtitle'], subtitle: ['The subtitle'] }
    expect(mapCrossrefItem(dup)?.title).toBe('Main title: The subtitle')
  })

  it('strips markup and entities from titles', () => {
    const item = { DOI: '10.1/x', title: ['Effects of <i>E. coli</i> on H<sub>2</sub>O &amp; air'] }
    expect(mapCrossrefItem(item)?.title).toBe('Effects of E. coli on H2O & air')
  })

  it('uses organisation names and given-name-only authors', () => {
    const item = {
      DOI: '10.1/x',
      title: ['T'],
      author: [
        { name: 'World Health Organization' },
        { given: 'Budi' },
        { family: 'Santoso', given: 'Ani' },
        {},
      ],
    }
    const r = mapCrossrefItem(item)
    expect(r?.authors).toEqual(['World Health Organization', 'Budi', 'Santoso'])
    expect(r?.authorsFull).toEqual(['World Health Organization', 'Budi', 'Ani Santoso'])
  })

  it('prefers a page range over an article number, and tolerates missing fields', () => {
    expect(
      mapCrossrefItem({ DOI: '10.1/x', title: ['T'], page: '304-312', 'article-number': '9' })
        ?.pages,
    ).toBe('304-312')
    const bare = mapCrossrefItem({ title: ['Only a title'] })
    expect(bare).toMatchObject({
      doi: null,
      url: null,
      authors: [],
      year: null,
      venue: null,
      pages: null,
    })
  })

  it('returns null for items without a usable title', () => {
    expect(mapCrossrefItem({ DOI: '10.1/x' })).toBeNull()
    expect(mapCrossrefItem({ DOI: '10.1/x', title: [] })).toBeNull()
    expect(mapCrossrefItem({ DOI: '10.1/x', title: ['  '] })).toBeNull()
    expect(mapCrossrefItem(null)).toBeNull()
    expect(mapCrossrefItem('text')).toBeNull()
  })

  it('treats a null year part as unknown', () => {
    expect(mapCrossrefItem({ title: ['T'], issued: { 'date-parts': [[null]] } })?.year).toBeNull()
  })
})

describe('CrossrefClient.getByDoi', () => {
  it('returns the record for a 200', async () => {
    const { client, calls } = setup([
      {
        match: urlHas('/works/10.1038/s41598'),
        respond: () => ok(fixtureText('crossref-work-walters.json')),
      },
    ])
    const r = await client.getByDoi(DOI)
    expect(r.found && r.record.title).toBe(WALTERS)
    expect(calls[0]?.url).toBe(`https://api.crossref.org/works/${DOI}`)
  })

  it('returns found:false for a 404', async () => {
    const { client } = setup([
      { match: urlHas('/works/'), respond: () => status(404, 'Resource not found.') },
    ])
    expect(await client.getByDoi('10.9999/nope')).toEqual({ found: false })
  })

  it('caches both hits and misses', async () => {
    const { client, calls } = setup([
      {
        match: urlHas('/works/10.1038'),
        respond: () => ok(fixtureText('crossref-work-walters.json')),
      },
      { match: urlHas('/works/10.9999'), respond: () => status(404) },
    ])
    await client.getByDoi(DOI)
    await client.getByDoi(DOI.toUpperCase()) // DOIs are case-insensitive
    await client.getByDoi('10.9999/nope')
    await client.getByDoi('10.9999/nope')
    expect(calls).toHaveLength(2)
  })

  it('throws ServiceUnavailableError (never a not-found) when the service keeps failing', async () => {
    const { client } = setup([
      { match: () => true, respond: () => status(503) },
      { match: () => true, respond: () => status(503) },
      { match: () => true, respond: () => status(503) },
    ])
    await expect(client.getByDoi(DOI)).rejects.toBeInstanceOf(ServiceUnavailableError)
  })

  it('does not cache a failure', async () => {
    const { client, calls } = setup([
      { match: () => true, respond: () => status(500) },
      { match: () => true, respond: () => status(500) },
      { match: () => true, respond: () => status(500) },
      { match: () => true, respond: () => ok(fixtureText('crossref-work-walters.json')) },
    ])
    await expect(client.getByDoi(DOI)).rejects.toBeInstanceOf(ServiceUnavailableError)
    expect((await client.getByDoi(DOI)).found).toBe(true)
    expect(calls).toHaveLength(4)
  })

  it('reports a malformed 200 body as a bad response', async () => {
    const { client } = setup([
      { match: () => true, respond: () => ok({ message: { nothing: 'useful' } }) },
    ])
    await expect(client.getByDoi(DOI)).rejects.toMatchObject({ code: 'bad_response' })
  })

  it('percent-encodes unusual DOI characters but keeps the slash', async () => {
    const { client, calls } = setup([{ match: () => true, respond: () => status(404) }])
    await client.getByDoi('10.1002/abc<def>#1')
    expect(calls[0]?.url).toBe('https://api.crossref.org/works/10.1002/abc%3Cdef%3E%231')
  })
})

describe('CrossrefClient.search', () => {
  it('maps recorded candidates in the order Crossref returns them', async () => {
    const { client } = setup([
      {
        match: urlHas('query.bibliographic'),
        respond: () => ok(fixtureText('crossref-search-walters.json')),
      },
    ])
    const found = await client.search({ title: WALTERS, firstAuthor: 'Walters', year: 2023 })
    expect(found).toHaveLength(5)
    expect(found[0]).toMatchObject({ doi: DOI, title: WALTERS, year: 2023 })
    expect(found.every((r) => r.source === 'crossref' && r.title !== '')).toBe(true)
  })

  it('asks for five rows and only the needed fields', async () => {
    const { client, calls } = setup([
      { match: () => true, respond: () => ok(fixtureText('crossref-search-walters.json')) },
    ])
    await client.search({ title: WALTERS, firstAuthor: 'Walters', year: 2023 })
    const url = new URL(calls[0]?.url as string)
    expect(url.searchParams.get('rows')).toBe('5')
    expect(url.searchParams.get('query.bibliographic')).toBe(`${WALTERS} Walters 2023`)
    expect(url.searchParams.get('select')).toContain('container-title')
    expect(url.searchParams.get('select')).not.toContain('reference')
  })

  it('returns an empty list when nothing is found, and caches it', async () => {
    const { client, calls } = setup([
      { match: () => true, respond: () => ok({ message: { items: [] } }) },
    ])
    expect(await client.search({ title: 'No such work' })).toEqual([])
    expect(await client.search({ title: 'no such work!' })).toEqual([]) // same normalized query
    expect(calls).toHaveLength(1)
  })

  it('skips items that have no title', async () => {
    const { client } = setup([
      {
        match: () => true,
        respond: () =>
          ok({ message: { items: [{ DOI: '10.1/a' }, { DOI: '10.1/b', title: ['Kept'] }] } }),
      },
    ])
    expect((await client.search({ title: 'x' })).map((r) => r.title)).toEqual(['Kept'])
  })

  it('reports a response without an items list as a bad response', async () => {
    const { client } = setup([{ match: () => true, respond: () => ok({ message: {} }) }])
    await expect(client.search({ title: 'x' })).rejects.toMatchObject({ code: 'bad_response' })
  })
})

describe('polite pool identification', () => {
  it('sends mailto and a User-Agent when configured', async () => {
    const { client, calls } = setup(
      [{ match: () => true, respond: () => ok({ message: { items: [] } }) }],
      'team@example.org',
    )
    await client.search({ title: 'x' })
    expect(new URL(calls[0]?.url as string).searchParams.get('mailto')).toBe('team@example.org')
    expect((calls[0]?.init?.headers as Record<string, string>)['user-agent']).toBe(
      'CekKutip/0.1 (mailto:team@example.org)',
    )
  })

  it('sends neither when no address is configured', async () => {
    const { client, calls } = setup([
      { match: () => true, respond: () => ok({ message: { items: [] } }) },
    ])
    await client.search({ title: 'x' })
    expect(new URL(calls[0]?.url as string).searchParams.has('mailto')).toBe(false)
    expect((calls[0]?.init?.headers as Record<string, string>)['user-agent']).toBe('CekKutip')
  })

  it('adapts its pacing to the limits Crossref advertises, never above the pool ceiling', async () => {
    const { fetchImpl } = stubFetch([
      {
        match: () => true,
        respond: () =>
          ok(
            { message: { items: [] } },
            {
              'x-rate-limit-limit': '5',
              'x-rate-limit-interval': '1s',
              'x-concurrency-limit': '1',
            },
          ),
      },
    ])
    const scheduler = new Scheduler({ maxConcurrent: 3, minIntervalMs: 100 })
    const client = createCrossrefClient({
      http: testHttp(fetchImpl),
      mailto: 'team@example.org',
      scheduler,
    })
    await client.search({ title: 'x' })
    expect(scheduler.limits).toEqual({ maxConcurrent: 1, minIntervalMs: 200 })

    // A (hypothetical) more generous header must not lift us above the polite ceiling.
    const { fetchImpl: f2 } = stubFetch([
      {
        match: () => true,
        respond: () =>
          ok(
            { message: { items: [] } },
            {
              'x-rate-limit-limit': '150',
              'x-rate-limit-interval': '1s',
              'x-concurrency-limit': '50',
            },
          ),
      },
    ])
    const s2 = new Scheduler({ maxConcurrent: 3, minIntervalMs: 100 })
    await createCrossrefClient({
      http: testHttp(f2),
      mailto: 'team@example.org',
      scheduler: s2,
    }).search({ title: 'y' })
    expect(s2.limits).toEqual({ maxConcurrent: 3, minIntervalMs: 100 })
  })

  it('uses the public-pool pace when there is no mailto', () => {
    const { fetchImpl } = stubFetch([])
    const scheduler = new Scheduler({ maxConcurrent: 1, minIntervalMs: 200 })
    createCrossrefClient({ http: testHttp(fetchImpl), scheduler })
    expect(scheduler.limits).toEqual({ maxConcurrent: 1, minIntervalMs: 200 })
  })
})
