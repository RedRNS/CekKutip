import type { Page } from '@playwright/test'
import {
  checkButton,
  expect,
  expectNoAxeViolations,
  expectNoHorizontalScroll,
  input,
  rows,
  test,
} from './helpers'

const A = 'Alpha, A. (2020). One.'
const B = 'Beta, B. (2021). Two.'
const C = 'Gamma, C. (2022). Three.'

// The first example reference, as a BibTeX entry. The formatter writes it back as the example line.
const WALTERS_BIB = `@article{walters2023,
  author = {Walters, William H. and Wilder, Esther Isabelle},
  title = {Fabrication and errors in the bibliographic citations generated by {ChatGPT}},
  journal = {Scientific Reports},
  year = 2023, volume = {13}, number = {1}, pages = {14045},
  doi = {10.1038/s41598-023-41032-5}
}`

const WALTERS_LINE =
  'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13(1), 14045. https://doi.org/10.1038/s41598-023-41032-5'

const fileInput = (page: Page) => page.locator('input[type="file"]')
const upload = (page: Page, name: string, content: string | Buffer, mimeType = 'text/plain') =>
  fileInput(page).setInputFiles({
    name,
    mimeType,
    buffer: typeof content === 'string' ? Buffer.from(content, 'utf8') : content,
  })

test.describe('upload a .txt or .bib file', () => {
  test('a .txt file goes into the box and is counted', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'refs.txt', `${A}\n\n${B}\n\n${C}\n`)
    await expect(input(page)).toHaveValue(`${A}\n\n${B}\n\n${C}`)
    await expect(page.getByText('3 found', { exact: true })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Added' })).toHaveText(
      'Added 3 references from refs.txt.',
    )
  })

  test('a .bib file becomes one reference per entry, and entries without a title are reported', async ({
    page,
  }) => {
    await page.goto('/')
    await upload(
      page,
      'refs.bib',
      `${WALTERS_BIB}\n\n@misc{notitle, author = {Doe, J.}, year = 2015}\n\n@book{b, author = {Doe, J.}, title = {A book}, publisher = {P}, year = 2015}`,
    )
    await expect(input(page)).toHaveValue(`${WALTERS_LINE}\n\nDoe, J. (2015). A book. P.`)
    await expect(page.getByText('2 found', { exact: true })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Added' })).toHaveText(
      'Added 2 references from refs.bib. 1 entry without a title was left out.',
    )
  })

  test('a file is added after what is already in the box', async ({ page }) => {
    await page.goto('/')
    await input(page).fill(A)
    await upload(page, 'more.txt', `${B}\n\n${C}`)
    await expect(input(page)).toHaveValue(`${A}\n\n${B}\n\n${C}`)
    await expect(page.getByText('3 found', { exact: true })).toBeVisible()
  })

  test('the same file can be chosen twice in a row', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'refs.txt', A)
    await upload(page, 'refs.txt', A)
    await expect(input(page)).toHaveValue(`${A}\n\n${A}`)
  })

  test('a .bib file that is uploaded and checked is found and verified', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'refs.bib', WALTERS_BIB)
    await expect(page.getByText('1 found', { exact: true })).toBeVisible()
    await checkButton(page).click()
    await expect(page.getByText('1 of 1 checked')).toBeVisible()
    await expect(rows(page).nth(0).locator('.verdict')).toHaveText('Verified')
  })

  test('refuses a file type it cannot read, and leaves the box alone', async ({ page }) => {
    await page.goto('/')
    await input(page).fill(A)
    await upload(page, 'refs.pdf', '%PDF-1.4', 'application/pdf')
    await expect(page.getByRole('alert').filter({ hasText: '.txt and .bib' })).toHaveText(
      'Only .txt and .bib files are supported.',
    )
    await expect(input(page)).toHaveValue(A)
  })

  test('refuses a file over 256 KB', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'big.txt', Buffer.alloc(256 * 1024 + 1, 'a'))
    await expect(page.getByRole('alert').filter({ hasText: '256 KB' })).toContainText(
      'That file is larger than 256 KB.',
    )
    await expect(input(page)).toHaveValue('')
  })

  test('says so when a file holds no references', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'empty.bib', 'this is not bibtex')
    await expect(page.getByRole('alert')).toHaveText('No references were found in that file.')
    await upload(page, 'blank.txt', '  \n  ')
    await expect(page.getByRole('alert')).toHaveText('No references were found in that file.')
  })

  test('clearing removes the upload message', async ({ page }) => {
    await page.goto('/')
    await upload(page, 'refs.txt', A)
    await expect(page.getByRole('status').filter({ hasText: 'Added' })).toBeVisible()
    await page.getByRole('button', { name: 'Clear' }).click()
    await expect(page.getByText(/^Added/)).toHaveCount(0)
  })

  test('the button opens the file chooser and the page has no accessibility violations', async ({
    page,
  }) => {
    await page.setViewportSize({ width: 375, height: 800 })
    await page.goto('/')
    const chooser = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: 'Upload .txt or .bib' }).click()
    expect((await chooser).isMultiple()).toBe(false)
    await upload(page, 'refs.txt', `${A}\n\n${B}`)
    await expect(page.getByText('2 found', { exact: true })).toBeVisible()
    await expectNoAxeViolations(page)
    await expectNoHorizontalScroll(page)
  })

  test('works in Indonesian', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Switch to Bahasa Indonesia' }).click()
    await expect(page.getByRole('button', { name: 'Unggah .txt atau .bib' })).toBeVisible()
    await upload(page, 'refs.txt', `${A}\n\n${B}`)
    await expect(page.getByRole('status').filter({ hasText: 'ditambahkan' })).toHaveText(
      '2 referensi ditambahkan dari refs.txt.',
    )
    await upload(page, 'refs.pdf', 'x', 'application/pdf')
    await expect(page.getByRole('alert')).toHaveText('Hanya berkas .txt dan .bib yang didukung.')
  })

  test('the privacy page says what happens to a chosen file', async ({ page }) => {
    await page.goto('/privacy')
    await expect(
      page.getByText('A .txt or .bib file you choose is read in your browser'),
    ).toBeVisible()
  })
})
