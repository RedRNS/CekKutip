import type { CheckStatus } from '@cekkutip/shared'
import { FieldTable } from '../components/FieldTable'
import type { FieldRow } from '../components/FieldTable'
import { PipelineDiagram } from '../components/PipelineDiagram'
import { VerdictLabel } from '../components/VerdictLabel'
import { usePageTitle } from '../hooks'
import { fmt, useI18n } from '../i18n'

/**
 * Worked example. The first two details are changed on purpose (year 2021 and Nature Communications);
 * the record side is the real Crossref entry for this article.
 * TODO(M4): confirm against a live pipeline run and record the verdict in docs/DECISIONS.md.
 */
const EXAMPLE_CITED =
  'Walters, W. H., & Wilder, E. I. (2021). Fabrication and errors in the bibliographic citations generated by ChatGPT. Nature Communications.'
const EXAMPLE_TITLE = 'Fabrication and errors in the bibliographic citations generated by ChatGPT'

export default function HowItWorks() {
  const { t } = useI18n()
  usePageTitle('how')

  const rows: FieldRow[] = [
    { field: 'title', cited: EXAMPLE_TITLE, found: EXAMPLE_TITLE, state: 'agree' },
    { field: 'authors', cited: 'Walters, Wilder', found: 'Walters, Wilder', state: 'agree' },
    {
      field: 'year',
      cited: '2021',
      found: '2023',
      state: 'differs',
      note: fmt(t.how.yearDiffers, { n: 2 }),
    },
    {
      field: 'venue',
      cited: 'Nature Communications',
      found: 'Scientific Reports',
      state: 'differs',
    },
    { field: 'doi', cited: null, found: '10.1038/s41598-023-41032-5', state: 'not_cited' },
  ]

  return (
    <>
      <div className="page-head">
        <h1>{t.how.h1}</h1>
        <p className="lede">{t.how.lede}</p>
      </div>

      <section className="section" aria-labelledby="diagram-title">
        <h2 id="diagram-title">{t.how.diagramTitle}</h2>
        <PipelineDiagram />
      </section>

      <section className="section" aria-labelledby="example-title">
        <h2 id="example-title">{t.how.exampleTitle}</h2>
        <p>{t.how.exampleIntro}</p>

        <div className="cited-block">
          <p className="cited-block__label">{t.how.exampleCitedLabel}</p>
          <p className="cited-block__text">{EXAMPLE_CITED}</p>
        </div>

        <ol className="example-steps">
          {t.how.exampleSteps.map((s, i) => (
            <li key={s.name}>
              <h3>
                <span className="mono example-steps__num">{String(i + 1).padStart(2, '0')}</span>{' '}
                {s.name}
              </h3>
              <p>{s.text}</p>
            </li>
          ))}
        </ol>

        <FieldTable
          rows={rows}
          tone="mismatch"
          labels={{
            caption: t.how.tableCaption,
            field: t.how.colField,
            cited: t.how.colCited,
            found: t.how.colFound,
            status: t.how.colStatus,
            fields: t.how.fields,
            states: t.how.states,
          }}
        />
        <div className="example-result">
          <span className="example-result__label">{t.how.exampleResult}</span>
          <VerdictLabel status="mismatch" />
          <span>{t.how.exampleResultText}</span>
        </div>
      </section>

      <section className="section" aria-labelledby="rules-title">
        <h2 id="rules-title">{t.how.rulesTitle}</h2>
        <p>{t.how.rulesIntro}</p>
        <table className="rules-table">
          <thead>
            <tr>
              <th scope="col">
                <span className="visually-hidden">#</span>
              </th>
              <th scope="col">{t.how.rulesColIf}</th>
              <th scope="col">{t.how.rulesColResult}</th>
            </tr>
          </thead>
          <tbody>
            {t.how.rules.map((r, i) => (
              <tr key={r.if}>
                <th scope="row" className="mono">
                  {i + 1}
                </th>
                <td>{r.if}</td>
                <td>
                  <VerdictLabel status={r.result as CheckStatus} />
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="muted">{t.how.checkFailedNote}</p>
      </section>

      <section className="section" aria-labelledby="limits-title">
        <h2 id="limits-title">{t.how.limitsTitle}</h2>
        <ul className="plain-list">
          {t.how.limits.map((l) => (
            <li key={l}>{l}</li>
          ))}
        </ul>
      </section>
    </>
  )
}
