import { describe, expect, it } from 'vitest'
import { parseBibtex } from '../bibtex.js'
import { bibtexFromReferences } from './bib-write.js'
import type { JournalArticle } from './types.js'

const person = (family: string, given = '', org = false) => ({ family, given, org })

const WALTERS: JournalArticle = {
  authors: [person('Walters', 'W. H.'), person('Wilder', 'E. I.')],
  etAl: false,
  namesUncertain: false,
  year: '2023',
  title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
  journal: 'Scientific Reports',
  volume: '13',
  issue: '1',
  pages: '14045',
  articleNumber: false,
  doi: '10.1038/s41598-023-41032-5',
  url: null,
}

const art = (over: Partial<JournalArticle>): JournalArticle => ({ ...WALTERS, ...over })
const labels = { header: '% Made by CekKutip.', kept: '% Not made into entries:' }
const write = (articles: JournalArticle[], withLabels = false) =>
  bibtexFromReferences(
    articles.map((article) => ({ article, text: 'text' })),
    withLabels ? labels : null,
  )

describe('bibtexFromReferences: one article', () => {
  it('writes the entry the way the product owner’s file is written: two spaces, equals signs lined up', () => {
    expect(write([WALTERS]).text).toBe(
      [
        '@article{walters2023,',
        '  author  = {Walters, W. H. and Wilder, E. I.},',
        '  title   = {Fabrication and errors in the bibliographic citations generated by {ChatGPT}},',
        '  journal = {Scientific Reports},',
        '  volume  = {13},',
        '  number  = {1},',
        '  pages   = {14045},',
        '  year    = {2023},',
        '  doi     = {10.1038/s41598-023-41032-5}',
        '}',
        '',
      ].join('\n'),
    )
  })

  it('writes a page range with two hyphens, and leaves out what the text did not have', () => {
    const text = write([art({ pages: '881-893', issue: null, volume: null, doi: null })]).text
    expect(text).toContain('pages   = {881--893}')
    expect(text).not.toContain('volume')
    expect(text).not.toContain('number')
    expect(text).not.toContain('doi')
  })

  it('uses the address only when there is no DOI', () => {
    expect(write([art({ doi: null, url: 'https://example.org/a' })]).text).toContain('url     = {https://example.org/a}')
    expect(write([art({ url: 'https://example.org/a' })]).text).not.toContain('url')
  })

  it('writes "et al." as "and others", an organisation in double braces, and a one-word name alone', () => {
    expect(write([art({ authors: [person('Wantoro', 'A.')], etAl: true })]).text).toContain(
      'author  = {Wantoro, A. and others}',
    )
    expect(write([art({ authors: [person('World Health Organization', '', true)] })]).text).toContain(
      'author  = {{World Health Organization}}',
    )
    expect(write([art({ authors: [person('Sugiyono')] })]).text).toContain('author  = {Sugiyono}')
  })

  it('writes initials the same way whichever way the text had them, and keeps full given names', () => {
    const text = write([
      art({ authors: [person('Walters', 'W.H.'), person('Wilder', 'E.I'), person('Putra', 'I. G. N. A.'), person('Wantoro', 'Agus'), person('Sartre', 'Jean-Paul'), person('Doe', 'William H.')] }),
    ]).text
    expect(text).toContain(
      'author  = {Walters, W. H. and Wilder, E. I. and Putra, I. G. N. A. and Wantoro, Agus and Sartre, Jean-Paul and Doe, William H.}',
    )
  })

  it('leaves out the year when there is none, and drops a letter after the year', () => {
    const none = write([art({ year: 'n.d.' })]).text
    expect(none).not.toContain('year')
    expect(none).toContain('@article{walters' + 'nd,')
    expect(write([art({ year: '2020a' })]).text).toContain('year    = {2020}')
  })

  it('writes a journal as it was written, with special characters escaped', () => {
    expect(write([art({ journal: 'Research & Development' })]).text).toContain('journal = {Research \\& Development}')
  })

  it('writes an entry that BibTeX reads back as the same data', () => {
    const [e] = parseBibtex(write([WALTERS]).text)
    expect(e).toMatchObject({
      type: 'article',
      key: 'walters2023',
      fields: {
        author: 'Walters, W. H. and Wilder, E. I.',
        journal: 'Scientific Reports',
        volume: '13',
        number: '1',
        pages: '14045',
        year: '2023',
        doi: '10.1038/s41598-023-41032-5',
      },
    })
  })
})

describe('bibtexFromReferences: the title', () => {
  const titleOf = (title: string) => /title {3}= \{(.*)\},/.exec(write([art({ title })]).text)?.[1]

  it.each([
    ['Application of LLM Agents in Recruitment', 'Application of {LLM} Agents in Recruitment'],
    ['A study of ChatGPT and YouTube', 'A study of {ChatGPT} and {YouTube}'],
    ['Learning in the COVID-19 era', 'Learning in the {COVID-19} era'],
    ['Evaluasi kinerja machine learning (ML) pada diabetes', 'Evaluasi kinerja machine learning ({ML}) pada diabetes'],
    ['Large Language Models (LLMs): a survey', 'Large Language Models ({LLMs}): a survey'],
    ['Self-Regulated Learning in E-Learning', 'Self-Regulated Learning in E-Learning'],
    ['A study of Indonesia and Java', 'A study of Indonesia and Java'],
    ['Already {LLM} protected', 'Already {LLM} protected'],
  ])('protects capitals that a style would lower: %s', (title, expected) => {
    expect(titleOf(title)).toBe(expected)
  })

  it.each([
    ['R&D and development', 'R\\&D and development'],
    ['A 50% increase', 'A 50\\% increase'],
    ['Cost in $ and # of items', 'Cost in \\$ and \\# of items'],
    ['snake_case names', 'snake\\_case names'],
  ])('escapes what LaTeX would take for markup: %s', (title, expected) => {
    expect(titleOf(title)).toBe(expected)
  })

  it('takes out braces that do not pair, so the file stays readable', () => {
    expect(titleOf('A title with { an open brace')).toBe('A title with  an open brace')
    expect(parseBibtex(write([art({ title: 'Broken } here' })]).text)).toHaveLength(1)
  })
})

describe('bibtexFromReferences: keys', () => {
  const keysOf = (articles: JournalArticle[]) => write(articles).keys

  it('is the first author’s family name and the year, in lower case without accents', () => {
    expect(keysOf([art({ authors: [person('Müller', 'A.')], year: '2021' })])).toEqual(['muller2021'])
    expect(keysOf([art({ authors: [person('Mahardika Pratama', 'I. G. A.')], year: '2022' })])).toEqual(['mahardikapratama2022'])
    expect(keysOf([art({ authors: [person('van Dis', 'E.')], year: '2023' })])).toEqual(['vandis2023'])
    expect(keysOf([art({ authors: [person('World Health Organization', '', true)], year: '2020' })])).toEqual(['world2020'])
  })

  it('gives letters to keys that would be the same, in the order of the list', () => {
    expect(
      keysOf([
        art({ authors: [person('Wei', 'J.')], year: '2022' }),
        art({ authors: [person('Wei', 'K.')], year: '2022' }),
        art({ authors: [person('Wei', 'L.')], year: '2023' }),
        art({ authors: [person('Wei', 'M.')], year: '2022' }),
      ]),
    ).toEqual(['wei2022a', 'wei2022b', 'wei2023', 'wei2022c'])
  })

  it('has a key even when there is nothing to make one from', () => {
    expect(keysOf([art({ authors: [person('日本', 'A.')], year: 'n.d.' })])).toEqual(['refnd'])
  })
})

describe('bibtexFromReferences: the file', () => {
  it('starts with the note, separates entries with a blank line, and ends with a line break', () => {
    const r = write([WALTERS, art({ authors: [person('Doe', 'J.')], year: '2020' })], true)
    expect(r.text.startsWith('% Made by CekKutip.\n\n@article{walters2023,')).toBe(true)
    expect(r.text).toContain('}\n\n@article{doe2020,')
    expect(r.text.endsWith('}\n')).toBe(true)
    expect(r.entries).toBe(2)
  })

  it('does not drop a reference it cannot make into an entry: it is written as a comment at the end', () => {
    const r = bibtexFromReferences(
      [
        { article: WALTERS, text: 'Walters ...' },
        { article: null, text: 'Sugiyono. (2017). Metode penelitian. Bandung: Alfabeta.' },
        { article: null, text: 'Text with\nbreaks that cannot be read' },
      ],
      labels,
    )
    expect(r.entries).toBe(1)
    expect(r.kept).toBe(2)
    expect(r.text).toContain(
      '\n% Not made into entries:\n% Sugiyono. (2017). Metode penelitian. Bandung: Alfabeta.\n% Text with breaks that cannot be read\n',
    )
    expect(parseBibtex(r.text)).toHaveLength(1) // a comment line is not an entry
  })

  it('gives a file with only the note when nothing could be made into an entry', () => {
    const r = bibtexFromReferences([{ article: null, text: 'asdf' }], labels)
    expect(r.entries).toBe(0)
    expect(r.text).toBe('% Made by CekKutip.\n\n% Not made into entries:\n% asdf\n')
  })

  it('gives an empty file for an empty list', () => {
    expect(bibtexFromReferences([], null)).toEqual({ text: '', entries: 0, keys: [], kept: 0 })
  })
})
