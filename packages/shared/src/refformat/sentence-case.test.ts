import { describe, expect, it } from 'vitest'
import { looksLikeTitleCase, toSentenceCase } from './sentence-case.js'

describe('toSentenceCase', () => {
  it.each([
    [
      'Evaluasi Kinerja Algoritma Machine Learning (ML) Menggunakan Seleksi Fitur Pada Klasifikasi Diabetes',
      'Evaluasi kinerja algoritma machine learning (ML) menggunakan seleksi fitur pada klasifikasi diabetes',
    ],
    [
      'Emotions In Storybooks: A Comparison Of Storybooks',
      'Emotions in storybooks: A comparison of storybooks',
    ],
    [
      'Using YouTube And iPhone For COVID-19 Learning',
      'Using YouTube and iPhone for COVID-19 learning',
    ],
    ['EVALUASI KINERJA ALGORITMA', 'Evaluasi kinerja algoritma'],
    ['Self-Regulated Learning In E-Learning', 'Self-regulated learning in e-learning'],
    ['Is It Real? A Study Of Things', 'Is it real? A study of things'],
    [
      'Fabrication and errors in the bibliographic citations generated by ChatGPT',
      'Fabrication and errors in the bibliographic citations generated by ChatGPT',
    ],
    ['The Role Of I And You', 'The role of I and you'],
  ])('%s', (input, expected) => {
    expect(toSentenceCase(input)).toBe(expected)
  })

  it('keeps single capital letters and words with digits', () => {
    expect(toSentenceCase('Vitamin D And Type 2 Diabetes In Region A')).toBe(
      'Vitamin D and type 2 diabetes in region A',
    )
  })

  it('leaves an empty title alone', () => {
    expect(toSentenceCase('')).toBe('')
  })
})

describe('looksLikeTitleCase', () => {
  it('is true when nearly every longer word starts with a capital', () => {
    expect(
      looksLikeTitleCase(
        'Evaluasi Kinerja Algoritma Machine Learning (ML) Menggunakan Seleksi Fitur Pada Klasifikasi Diabetes',
      ),
    ).toBe(true)
    expect(looksLikeTitleCase('Emotions In Storybooks: A Comparison Of Storybooks')).toBe(true)
  })

  it('is false for a title in sentence case', () => {
    expect(
      looksLikeTitleCase('Fabrication and errors in the bibliographic citations generated by ChatGPT'),
    ).toBe(false)
    expect(looksLikeTitleCase('Evaluasi kinerja algoritma machine learning (ML)')).toBe(false)
  })

  it('is false for a short title, which gives too little to go on', () => {
    expect(looksLikeTitleCase('Machine Learning')).toBe(false)
    expect(looksLikeTitleCase('Metode Penelitian Kuantitatif')).toBe(false)
  })

  it('is true for a title in capitals only, which needs the same change', () => {
    expect(looksLikeTitleCase('EVALUASI KINERJA ALGORITMA MACHINE LEARNING MENGGUNAKAN')).toBe(true)
  })
})
