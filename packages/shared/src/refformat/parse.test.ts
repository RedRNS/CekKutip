import { describe, expect, it } from 'vitest'
import { parseReference } from './parse.js'

const GRADY =
  'Grady, J. S., Her, M., Moreno, G., Perez, C., & Yelinek, J. (2019). Emotions in storybooks: A comparison of storybooks that represent ethnic and racial groups in the United States. Psychology of Popular Media Culture, 8(3), 207–217. https://doi.org/10.1037/ppm0000185'
const GRADY_TITLE =
  'Emotions in storybooks: A comparison of storybooks that represent ethnic and racial groups in the United States'

function ok(raw: string) {
  const r = parseReference(raw)
  if (!r.ok) throw new Error(`expected a journal article, got ${r.reason}: ${r.cleaned}`)
  return r
}
const fail = (raw: string) => {
  const r = parseReference(raw)
  if (r.ok) throw new Error(`expected a refusal, got ${JSON.stringify(r.ref)}`)
  return r
}

describe('parseReference: a journal article in APA form', () => {
  it('reads every part', () => {
    const { ref } = ok(GRADY)
    expect(ref.authors.map((p) => p.family)).toEqual(['Grady', 'Her', 'Moreno', 'Perez', 'Yelinek'])
    expect(ref).toMatchObject({
      year: '2019',
      title: GRADY_TITLE,
      journal: 'Psychology of Popular Media Culture',
      volume: '8',
      issue: '3',
      pages: '207-217',
      articleNumber: false,
      doi: '10.1037/ppm0000185',
      etAl: false,
    })
  })

  it('keeps the parts as they were written, with their punctuation', () => {
    const { written } = ok(GRADY)
    expect(written).toEqual({
      authors: 'Grady, J. S., Her, M., Moreno, G., Perez, C., & Yelinek, J.',
      year: '(2019).',
      title: `${GRADY_TITLE}.`,
      source: 'Psychology of Popular Media Culture, 8(3), 207–217.',
      doi: 'https://doi.org/10.1037/ppm0000185',
    })
  })

  it('strips italics marks that come from pasting Markdown', () => {
    const { ref } = ok('Doe, J. (2020). A title. *Journal of Things*, *8*(3), 1-10.')
    expect(ref).toMatchObject({ journal: 'Journal of Things', volume: '8', issue: '3' })
    expect(ok('Doe, J. (2020). A title. _Journal of Things_, 8(3), 1-10.').ref.journal).toBe(
      'Journal of Things',
    )
  })
})

describe('parseReference: other shapes of the same article', () => {
  it('reads a careless one: no commas, no brackets around nothing, "doi:" label', () => {
    const { ref } = ok(
      'Walters, W.H. & Wilder, E.I (2023) Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports 13(1) 14045 doi:10.1038/s41598-023-41032-5',
    )
    expect(ref).toMatchObject({
      year: '2023',
      journal: 'Scientific Reports',
      volume: '13',
      issue: '1',
      pages: '14045',
      doi: '10.1038/s41598-023-41032-5',
    })
    expect(ref.authors.map((p) => [p.family, p.given])).toEqual([
      ['Walters', 'W.H.'],
      ['Wilder', 'E.I'],
    ])
  })

  it('reads an IEEE reference, with its number, quoted title, vol./no. and "Art. no."', () => {
    const { ref, written, cleaned } = ok(
      '[4] W. H. Walters and E. I. Wilder, "Fabrication and errors in the bibliographic citations generated by ChatGPT," Scientific Reports, vol. 13, no. 1, Art. no. 14045, 2023, doi: 10.1038/s41598-023-41032-5.',
    )
    expect(ref).toMatchObject({
      year: '2023',
      title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
      journal: 'Scientific Reports',
      volume: '13',
      issue: '1',
      pages: '14045',
      articleNumber: true,
      doi: '10.1038/s41598-023-41032-5',
    })
    expect(ref.authors.map((p) => [p.family, p.given])).toEqual([
      ['Walters', 'W. H.'],
      ['Wilder', 'E. I.'],
    ])
    expect(written.authors).toBe('W. H. Walters and E. I. Wilder')
    expect(cleaned.startsWith('[4]')).toBe(false)
  })

  it('reads a Harvard reference: quoted title with a question mark, pp., and "Available at:"', () => {
    const { ref } = ok(
      "Barke, M. and Mowl, G. (2016) 'Málaga – a failed resort of the early twentieth century?', Journal of Tourism History, 2(3), pp. 187–212. Available at: https://doi.org/10.1080/1755182X.2010.523145.",
    )
    expect(ref).toMatchObject({
      year: '2016',
      title: 'Málaga – a failed resort of the early twentieth century?',
      journal: 'Journal of Tourism History',
      volume: '2',
      issue: '3',
      pages: '187-212',
      doi: '10.1080/1755182X.2010.523145',
    })
  })

  it('reads vol., no., and pp. written out in an author-date reference', () => {
    const { ref } = ok('Doe, J. (2020). A title. Journal of X, vol. 8, no. 3, pp. 207–217.')
    expect(ref).toMatchObject({ journal: 'Journal of X', volume: '8', issue: '3', pages: '207-217' })
  })

  it('reads the Vancouver-like "Journal 8(3):207-17"', () => {
    const { ref } = ok('Doe, J. (2020). A title. Journal of X 8(3):207-17.')
    expect(ref).toMatchObject({ journal: 'Journal of X', volume: '8', issue: '3', pages: '207-17' })
  })

  it('reads a volume without an issue, and an article with no pages', () => {
    expect(ok('Doe, J. (2020). A title. Journal of X, 8, 207-217.').ref).toMatchObject({
      volume: '8',
      issue: null,
      pages: '207-217',
    })
    expect(ok('Doe, J. (2020). A title. Journal of X, 8(3).').ref).toMatchObject({
      volume: '8',
      issue: '3',
      pages: null,
    })
  })

  it('reads a title that has abbreviations and a question mark', () => {
    expect(
      ok('Smith, J. (2020). Comparing U.S. and E.U. policies: A review. Journal of Policy, 5(2), 1-10.')
        .ref.title,
    ).toBe('Comparing U.S. and E.U. policies: A review')
    expect(ok('Doe, J. (2020). Is it real? Journal of Things, 1(1), 1-2.').ref.title).toBe(
      'Is it real?',
    )
  })

  it('reads an Indonesian reference that has "et al." and a journal with an abbreviation in it', () => {
    const { ref } = ok(
      'Wantoro, A., et al. (2025). Evaluasi Kinerja Algoritma Machine Learning (ML) Menggunakan Seleksi Fitur Pada Klasifikasi Diabetes. JIP (Jurnal Inform. Polinema), 11(3).',
    )
    expect(ref).toMatchObject({
      etAl: true,
      year: '2025',
      title:
        'Evaluasi Kinerja Algoritma Machine Learning (ML) Menggunakan Seleksi Fitur Pada Klasifikasi Diabetes',
      journal: 'JIP (Jurnal Inform. Polinema)',
      volume: '11',
      issue: '3',
      pages: null,
    })
    expect(ref.authors.map((p) => [p.family, p.given])).toEqual([['Wantoro', 'A.']])
  })

  it('reads an organisation as the author, and "n.d." and a letter after the year', () => {
    const org = ok(
      'World Health Organization. (2020). Global report. Bulletin of the World Health Organization, 98(1), 1-5.',
    )
    expect(org.ref.authors).toEqual([{ family: 'World Health Organization', given: '', org: true }])
    expect(ok('Doe, J. (n.d.). A title. Journal of X, 1(1), 1-2.').ref.year).toBe('n.d.')
    expect(ok('Doe, J. (2020a). A title. Journal of X, 1(1), 1-2.').ref.year).toBe('2020a')
  })

  it('flags names whose order it had to guess', () => {
    const r = ok('Agus Wantoro and Aviv Fitria Yulia (2025). A title. Journal of X, 1(1), 1-2.')
    expect(r.ref.namesUncertain).toBe(true)
  })

  it.each([
    ['https://doi.org/10.1000/xyz.123.', '10.1000/xyz.123'],
    ['http://dx.doi.org/10.1000/xyz.123', '10.1000/xyz.123'],
    ['DOI: 10.1000/xyz.123', '10.1000/xyz.123'],
    ['doi:10.1000/xyz.123.', '10.1000/xyz.123'],
    ['Available at: https://doi.org/10.1000/xyz.123.', '10.1000/xyz.123'],
  ])('finds the DOI in "%s"', (tail, doi) => {
    expect(ok(`Doe, J. (2020). A title. Journal of X, 1(1), 1-2. ${tail}`).ref.doi).toBe(doi)
  })

  it.each([
    ['[12] ', 'Doe, J. (2020).'],
    ['12. ', 'Doe, J. (2020).'],
    ['(3) ', 'Doe, J. (2020).'],
    ['3) ', 'Doe, J. (2020).'],
  ])('drops the list number "%s"', (marker, start) => {
    const r = ok(`${marker}${start} A title. Journal of X, 1(1), 1-2.`)
    expect(r.cleaned.startsWith(start)).toBe(true)
    expect(r.ref.authors[0]?.family).toBe('Doe')
  })

  it('collapses spaces and breaks, and straightens curly quotes', () => {
    const { ref } = ok(
      'Doe,   J.\n(2020).  “A   title”,\n Journal of X, 1(1), 1-2.',
    )
    expect(ref.title).toBe('A title')
    expect(ref.journal).toBe('Journal of X')
  })
})

describe('parseReference: what it will not rewrite', () => {
  it.each([
    [
      'a book',
      'Sugiyono. (2017). Metode penelitian kuantitatif, kualitatif, dan R&D. Bandung: Alfabeta.',
    ],
    [
      'a thesis',
      'Wijaya, A. (2020). Dampak media sosial terhadap prestasi belajar [Skripsi, Universitas Contoh]. Repositori Universitas Contoh.',
    ],
    [
      'a web page',
      'World Health Organization. (2020). Coronavirus disease (COVID-19). https://www.who.int/health-topics/coronavirus',
    ],
    [
      'a conference paper',
      'Vaswani, A., et al. (2017). Attention is all you need. Proceedings of the 31st Conference on Neural Information Processing Systems, 5998-6008.',
    ],
    [
      'a conference paper in Indonesian',
      'Putra, B. (2021). Sistem informasi desa. Prosiding Seminar Nasional Teknologi Informasi, 12(1), 1-8.',
    ],
  ])('says %s is not a journal article, and still cleans the text', (_what, raw) => {
    const r = fail(raw)
    expect(r.reason).toBe('not_journal_article')
    expect(r.cleaned).toContain(raw.slice(0, 20))
  })

  it('does not take the journal "Proceedings of the National Academy of Sciences" for a conference', () => {
    expect(
      ok(
        'Doe, J. (2020). A title. Proceedings of the National Academy of Sciences, 117(5), 1-8.',
      ).ref.journal,
    ).toBe('Proceedings of the National Academy of Sciences')
  })

  it.each([
    ['text that is not a reference', 'asdf qwer'],
    ['a reference with no year', 'Doe, J. A title. Journal of X, 1(1), 1-2.'],
    ['an empty text', '   '],
    ['a year only', '(2020).'],
  ])('says it cannot read %s', (_what, raw) => {
    expect(fail(raw).reason).toBe('unreadable')
  })

  it('shows the DOI as a link in the cleaned text of a reference it does not rewrite', () => {
    const r = fail('Sugiyono. (2017). Metode penelitian. Bandung: Alfabeta. doi:10.1000/abc')
    expect(r.cleaned).toContain('https://doi.org/10.1000/abc')
    expect(r.cleaned).not.toContain('doi:10.1000')
  })
})

describe('parseReference: a paper in a book or proceedings, written with "In"', () => {
  it.each([
    [
      'Wei, J., et al. (2022). Chain-Of-Thought Prompting Elicits Reasoning in Large Language Models. In Advances in Neural Information Processing Systems 35 (pp. 24824-24837).',
    ],
    [
      'Wang, N., et al. (2024). RoleLLM: Benchmarking abilities. In Findings of the Association for Computational Linguistics ACL 2024 (pp. 14743-14777).',
    ],
    ['Doe, J. (2020). A chapter title. In Handbook of Things, 12-30.'],
  ])('is not a journal article: %s', (raw) => {
    expect(fail(raw).reason).toBe('not_journal_article')
  })

  it('still reads a journal whose name starts with "In" when it has a volume', () => {
    const { ref } = ok('Doe, J. (2020). A title. In Vitro Cellular & Developmental Biology, 55(3), 1-10.')
    expect(ref).toMatchObject({ journal: 'In Vitro Cellular & Developmental Biology', volume: '55', issue: '3' })
  })
})

describe('parseReference: titles with a question mark and a subtitle', () => {
  it('keeps a plain subtitle after "?" in the title', () => {
    expect(
      ok('Doe, J. (2020). Is it real? A study of things. Journal of Things, 1(1), 1-2.').ref.title,
    ).toBe('Is it real? A study of things')
  })

  it('ends the title at "?" when what follows is the journal', () => {
    const { ref } = ok('Doe, J. (2020). Is it real? Journal of Things, 1(1), 1-2.')
    expect(ref.title).toBe('Is it real?')
    expect(ref.journal).toBe('Journal of Things')
  })
})

describe('parseReference: text that is huge or built to be slow', () => {
  it('refuses a reference of more than 2000 characters without reading it', () => {
    const r = fail(`Doe, J. (2020). ${'word '.repeat(500)}. Journal of X, 1(1), 1-2.`)
    expect(r.reason).toBe('unreadable')
  })

  it.each([
    ['many full stops', 'a. '.repeat(600)],
    ['many brackets', '('.repeat(1500)],
    ['many quotes', '"'.repeat(1500)],
    ['many initials', 'A. '.repeat(600) + '(2020). T. J, 1(1), 1-2.'],
    ['many commas', 'Doe, '.repeat(350) + '(2020). T. J, 1(1), 1-2.'],
    ['a long run with no spaces', 'x'.repeat(1900)],
  ])('answers quickly for %s', (_name, text) => {
    const t0 = performance.now()
    parseReference(text)
    expect(performance.now() - t0).toBeLessThan(500)
  })
})
