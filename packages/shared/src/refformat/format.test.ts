import { describe, expect, it } from 'vitest'
import { formatArticle } from './format.js'
import { html, markdown, plain } from './pieces.js'
import type { JournalArticle } from './types.js'

const person = (family: string, given = '', org = false) => ({ family, given, org })

const WALTERS: JournalArticle = {
  authors: [person('Walters', 'W. H.'), person('Wilder', 'E. I.')],
  etAl: false,
  namesUncertain: false,
  year: '2023',
  title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
  journal: 'Scientific Reports',
  volume: '13',
  issue: '1',
  pages: '14045',
  articleNumber: false,
  doi: '10.1038/s41598-023-41032-5',
  url: null,
}

// From the APA Style site (journal article references).
const GRADY: JournalArticle = {
  authors: [
    person('Grady', 'J. S.'),
    person('Her', 'M.'),
    person('Moreno', 'G.'),
    person('Perez', 'C.'),
    person('Yelinek', 'J.'),
  ],
  etAl: false,
  namesUncertain: false,
  year: '2019',
  title:
    'Emotions in storybooks: A comparison of storybooks that represent ethnic and racial groups in the United States',
  journal: 'Psychology of Popular Media Culture',
  volume: '8',
  issue: '3',
  pages: '207-217',
  articleNumber: false,
  doi: '10.1037/ppm0000185',
  url: null,
}

// From the Open University's Harvard (Cite Them Right) guide.
const BARKE: JournalArticle = {
  authors: [person('Barke', 'M.'), person('Mowl', 'G.')],
  etAl: false,
  namesUncertain: false,
  year: '2016',
  title: 'Málaga – a failed resort of the early twentieth century?',
  journal: 'Journal of Tourism History',
  volume: '2',
  issue: '3',
  pages: '187-212',
  articleNumber: false,
  doi: '10.1080/1755182X.2010.523145',
  url: null,
}

const art = (over: Partial<JournalArticle>): JournalArticle => ({ ...WALTERS, ...over })
const fmt = (a: JournalArticle, style: 'apa' | 'ieee' | 'harvard', sentenceCase = false) =>
  formatArticle(a, style, { sentenceCase })

const EN = '–'

describe('APA 7', () => {
  it('writes the official example exactly, with the journal and volume in italics', () => {
    expect(markdown(fmt(GRADY, 'apa').pieces)).toBe(
      `Grady, J. S., Her, M., Moreno, G., Perez, C., & Yelinek, J. (2019). Emotions in storybooks: A comparison of storybooks that represent ethnic and racial groups in the United States. *Psychology of Popular Media Culture*, *8*(3), 207${EN}217. https://doi.org/10.1037/ppm0000185`,
    )
  })

  it('writes an article number as "Article N" (the number was read as an article number)', () => {
    const r = fmt(WALTERS, 'apa')
    expect(markdown(r.pieces)).toBe(
      'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. *Scientific Reports*, *13*(1), Article 14045. https://doi.org/10.1038/s41598-023-41032-5',
    )
    expect(r.notes).toContain('article_number_assumed')
  })

  it('does not say it assumed anything when the text itself said it was an article number', () => {
    const r = fmt(art({ pages: '123', articleNumber: true }), 'apa')
    expect(plain(r.pieces)).toContain('Article 123.')
    expect(r.notes).not.toContain('article_number_assumed')
  })

  it.each([
    [1, 'Smith, J. (2020).'],
    [2, 'Smith, J., & Lee, K. (2020).'],
    [3, 'Smith, J., Lee, K., & Park, L. (2020).'],
  ])('lists %i authors', (n, start) => {
    const authors = [person('Smith', 'J.'), person('Lee', 'K.'), person('Park', 'L.')].slice(0, n)
    expect(plain(fmt(art({ authors, year: '2020' }), 'apa').pieces).startsWith(start)).toBe(true)
  })

  it('lists up to 20 authors, and for 21 or more writes the first 19, "...", and the last', () => {
    const many = Array.from({ length: 21 }, (_, i) => person(`Name${i + 1}`, 'A.'))
    const text = plain(fmt(art({ authors: many }), 'apa').pieces)
    expect(text.startsWith('Name1, A., Name2, A.')).toBe(true)
    expect(text).toContain('Name19, A., ... Name21, A. (2023).')
    expect(text).not.toContain('Name20')
    const twenty = plain(fmt(art({ authors: many.slice(0, 20) }), 'apa').pieces)
    expect(twenty).toContain('Name19, A., & Name20, A. (2023).')
    expect(fmt(art({ authors: many }), 'apa').notes).toContain('authors_shortened')
  })

  it('keeps "et al." that was in the text, and says it cannot add the other names', () => {
    const r = fmt(art({ authors: [person('Wantoro', 'A.')], etAl: true }), 'apa')
    expect(plain(r.pieces).startsWith('Wantoro, A., et al. (2023).')).toBe(true)
    expect(r.notes).toContain('et_al_kept')
  })

  it('writes an organisation as the author, and "(n.d.)" for no date', () => {
    const text = plain(
      fmt(art({ authors: [person('World Health Organization', '', true)], year: 'n.d.' }), 'apa')
        .pieces,
    )
    expect(text.startsWith('World Health Organization. (n.d.). Fabrication')).toBe(true)
  })

  it('writes a one-word author with a full stop', () => {
    expect(
      plain(fmt(art({ authors: [person('Sugiyono')], year: '2017' }), 'apa').pieces).startsWith(
        'Sugiyono. (2017).',
      ),
    ).toBe(true)
  })

  it('writes initials from full given names, and keeps hyphenated ones together', () => {
    const text = plain(
      fmt(
        art({ authors: [person('Wantoro', 'Agus'), person('Sartre', 'Jean-Paul')] }),
        'apa',
      ).pieces,
    )
    expect(text.startsWith('Wantoro, A., & Sartre, J.-P. (2023).')).toBe(true)
  })

  it('does not add a full stop after a title that ends in "?" or "!"', () => {
    expect(plain(fmt(art({ title: 'Is it real?' }), 'apa').pieces)).toContain('(2023). Is it real? ')
    expect(plain(fmt(art({ title: 'Is it real!' }), 'apa').pieces)).toContain('(2023). Is it real! ')
  })

  it('writes a volume without an issue, an issue without pages, and a single page', () => {
    expect(plain(fmt(art({ issue: null, pages: '10-20', doi: null }), 'apa').pieces)).toMatch(
      /Scientific Reports, 13, 10–20\.$/,
    )
    expect(plain(fmt(art({ pages: null, doi: null }), 'apa').pieces)).toMatch(
      /Scientific Reports, 13\(1\)\.$/,
    )
    expect(plain(fmt(art({ pages: '123', doi: null }), 'apa').pieces)).toMatch(
      /Scientific Reports, 13\(1\), 123\.$/,
    )
  })

  it('ends with the link and no full stop, and uses the address when there is no DOI', () => {
    expect(plain(fmt(WALTERS, 'apa').pieces).endsWith('s41598-023-41032-5')).toBe(true)
    expect(
      plain(fmt(art({ doi: null, url: 'https://example.org/a' }), 'apa').pieces).endsWith(
        'https://example.org/a',
      ),
    ).toBe(true)
    expect(plain(fmt(art({ doi: null }), 'apa').pieces).endsWith('Article 14045.')).toBe(true)
  })

  it('italicises exactly the journal and the volume', () => {
    const italic = fmt(GRADY, 'apa')
      .pieces.filter((p) => p.italic)
      .map((p) => p.text)
    expect(italic).toEqual(['Psychology of Popular Media Culture', '8'])
  })
})

describe('IEEE', () => {
  it('puts the initials first, quotes the title with the comma inside, and ends with the DOI', () => {
    const r = fmt(WALTERS, 'ieee')
    expect(markdown(r.pieces)).toBe(
      'W. H. Walters and E. I. Wilder, "Fabrication and errors in the bibliographic citations generated by ChatGPT," *Scientific Reports*, vol. 13, no. 1, Art. no. 14045, 2023, doi: 10.1038/s41598-023-41032-5.',
    )
  })

  it('writes a page range with "pp." and an en dash', () => {
    expect(markdown(fmt(GRADY, 'ieee').pieces)).toBe(
      `J. S. Grady, M. Her, G. Moreno, C. Perez, and J. Yelinek, "Emotions in storybooks: A comparison of storybooks that represent ethnic and racial groups in the United States," *Psychology of Popular Media Culture*, vol. 8, no. 3, pp. 207${EN}217, 2019, doi: 10.1037/ppm0000185.`,
    )
  })

  it('writes one page as "p."', () => {
    expect(plain(fmt(art({ pages: '123', doi: null }), 'ieee').pieces)).toMatch(/, p\. 123, 2023\.$/)
  })

  it('uses "and" for two, a comma before "and" for three to six, and "et al." for more than six', () => {
    const people = Array.from({ length: 7 }, (_, i) => person(`N${i + 1}`, 'A.'))
    expect(plain(fmt(art({ authors: people.slice(0, 2) }), 'ieee').pieces)).toMatch(
      /^A\. N1 and A\. N2, "/,
    )
    expect(plain(fmt(art({ authors: people.slice(0, 6) }), 'ieee').pieces)).toMatch(
      /^A\. N1, A\. N2, A\. N3, A\. N4, A\. N5, and A\. N6, "/,
    )
    const seven = fmt(art({ authors: people }), 'ieee')
    expect(plain(seven.pieces)).toMatch(/^A\. N1 et al\., "/)
    expect(seven.notes).toContain('authors_shortened')
  })

  it('writes "et al." that was in the text', () => {
    const r = fmt(art({ authors: [person('Wantoro', 'A.')], etAl: true }), 'ieee')
    expect(plain(r.pieces)).toMatch(/^A\. Wantoro et al\., "/)
    expect(r.notes).toContain('et_al_kept')
  })

  it('keeps a title that ends in "?" and leaves the comma out', () => {
    expect(plain(fmt(art({ title: 'Is it real?' }), 'ieee').pieces)).toContain('"Is it real?" ')
  })

  it('leaves the year out when there is none, and has no DOI part without a DOI', () => {
    const text = plain(fmt(art({ year: 'n.d.', doi: null }), 'ieee').pieces)
    expect(text).toMatch(/Art\. no\. 14045\.$/)
  })

  it('always says that journal names are abbreviated in IEEE and that it did not do it', () => {
    expect(fmt(WALTERS, 'ieee').notes).toContain('ieee_journal_abbreviation')
    expect(fmt(WALTERS, 'apa').notes).not.toContain('ieee_journal_abbreviation')
  })

  it('italicises only the journal', () => {
    expect(
      fmt(WALTERS, 'ieee')
        .pieces.filter((p) => p.italic)
        .map((p) => p.text),
    ).toEqual(['Scientific Reports'])
  })
})

describe('Harvard (Cite Them Right)', () => {
  it('writes the Open University example exactly', () => {
    expect(markdown(fmt(BARKE, 'harvard').pieces)).toBe(
      `Barke, M. and Mowl, G. (2016) 'Málaga – a failed resort of the early twentieth century?', *Journal of Tourism History*, 2(3), pp. 187${EN}212. Available at: https://doi.org/10.1080/1755182X.2010.523145.`,
    )
  })

  it('writes initials without spaces, "and" without a comma, and an article number as "article N"', () => {
    expect(markdown(fmt(WALTERS, 'harvard').pieces)).toBe(
      "Walters, W.H. and Wilder, E.I. (2023) 'Fabrication and errors in the bibliographic citations generated by ChatGPT', *Scientific Reports*, 13(1), article 14045. Available at: https://doi.org/10.1038/s41598-023-41032-5.",
    )
  })

  it('lists every author, however many, and joins the last with "and" and no comma', () => {
    expect(plain(fmt(GRADY, 'harvard').pieces)).toMatch(
      /^Grady, J\.S\., Her, M\., Moreno, G\., Perez, C\. and Yelinek, J\. \(2019\) '/,
    )
  })

  it('writes "et al." that was in the text in italics', () => {
    const r = fmt(art({ authors: [person('Wantoro', 'A.')], etAl: true }), 'harvard')
    expect(markdown(r.pieces).startsWith('Wantoro, A. *et al.* (2023) ')).toBe(true)
    expect(r.notes).toContain('et_al_kept')
  })

  it('writes an organisation without a full stop, and "(no date)"', () => {
    const text = plain(
      fmt(art({ authors: [person('World Health Organization', '', true)], year: 'n.d.' }), 'harvard')
        .pieces,
    )
    expect(text.startsWith("World Health Organization (no date) 'Fabrication")).toBe(true)
  })

  it('writes one page as "p." and no pages as nothing', () => {
    expect(plain(fmt(art({ pages: '123', doi: null }), 'harvard').pieces)).toMatch(
      /13\(1\), p\. 123\.$/,
    )
    expect(plain(fmt(art({ pages: null, doi: null }), 'harvard').pieces)).toMatch(/13\(1\)\.$/)
  })

  it('uses the address when there is no DOI', () => {
    expect(
      plain(fmt(art({ doi: null, url: 'https://example.org/a' }), 'harvard').pieces),
    ).toMatch(/Available at: https:\/\/example\.org\/a\.$/)
  })

  it('italicises only the journal', () => {
    expect(
      fmt(BARKE, 'harvard')
        .pieces.filter((p) => p.italic)
        .map((p) => p.text),
    ).toEqual(['Journal of Tourism History'])
  })
})

describe('the title', () => {
  const TITLE_CASE = 'Evaluasi Kinerja Algoritma Machine Learning (ML) Menggunakan Seleksi Fitur Pada Klasifikasi Diabetes'
  const SENTENCE =
    'Evaluasi kinerja algoritma machine learning (ML) menggunakan seleksi fitur pada klasifikasi diabetes'

  it('is left as written, with a note when it looks like Title Case', () => {
    const r = fmt(art({ title: TITLE_CASE }), 'apa')
    expect(plain(r.pieces)).toContain(`(2023). ${TITLE_CASE}.`)
    expect(r.notes).toContain('title_case')
    expect(r.notes).not.toContain('sentence_case_applied')
  })

  it('is put into sentence case when asked, with a note to check the names in it', () => {
    for (const style of ['apa', 'ieee', 'harvard'] as const) {
      const r = fmt(art({ title: TITLE_CASE }), style, true)
      expect(plain(r.pieces)).toContain(SENTENCE)
      expect(r.notes).toContain('sentence_case_applied')
      expect(r.notes).not.toContain('title_case')
    }
  })

  it('says nothing about case when the title is already in sentence case', () => {
    const r = fmt(WALTERS, 'apa', true)
    expect(r.notes).not.toContain('title_case')
    expect(r.notes).not.toContain('sentence_case_applied')
  })
})

describe('parts and pieces', () => {
  it('gives each part as plain text, for comparing with what was written', () => {
    expect(fmt(WALTERS, 'apa').parts).toEqual({
      authors: 'Walters, W. H., & Wilder, E. I.',
      year: '(2023).',
      title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT.',
      source: 'Scientific Reports, 13(1), Article 14045.',
      doi: 'https://doi.org/10.1038/s41598-023-41032-5',
    })
  })

  it('turns pieces into plain text, Markdown, and escaped HTML', () => {
    const pieces = [{ text: 'A & B <x> ' }, { text: 'Journal', italic: true }, { text: '.' }]
    expect(plain(pieces)).toBe('A & B <x> Journal.')
    expect(markdown(pieces)).toBe('A & B <x> *Journal*.')
    expect(html(pieces)).toBe('A &amp; B &lt;x&gt; <i>Journal</i>.')
  })
})
