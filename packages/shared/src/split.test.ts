import { describe, expect, it } from 'vitest'
import {
  checkLimits,
  joinReferences,
  mergeWithPrevious,
  replaceReference,
  splitReferences,
} from './split.js'

const A =
  'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in citations. Scientific Reports, 13, 14045.'
const B =
  'Vaswani, A., Shazeer, N., & Polosukhin, I. (2017). Attention is all you need. NeurIPS, 30.'
const C =
  'Wijaya, A. (2020). Pengaruh media sosial terhadap prestasi belajar. Jurnal Pendidikan, 4(2), 10-20.'

describe('splitReferences', () => {
  it('splits on blank lines', () => {
    expect(splitReferences(`${A}\n\n${B}\n\n\n${C}`)).toEqual([A, B, C])
  })

  it('joins wrapped lines inside a blank-line block', () => {
    const wrapped =
      'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors\nin citations. Scientific Reports, 13.'
    expect(splitReferences(`${wrapped}\n\n${B}`)).toEqual([
      'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in citations. Scientific Reports, 13.',
      B,
    ])
  })

  it.each([
    ['1.', '2.', '3.'],
    ['[1]', '[2]', '[3]'],
    ['(1)', '(2)', '(3)'],
    ['1)', '2)', '3)'],
  ])('splits numbered lists and strips %s', (n1, n2, n3) => {
    expect(splitReferences(`${n1} ${A}\n${n2} ${B}\n${n3} ${C}`)).toEqual([A, B, C])
  })

  it('keeps a wrapped numbered reference together', () => {
    const text =
      '1. Walters, W. H. (2023). Fabrication and errors\n   in citations. Scientific Reports.\n2. ' +
      B
    expect(splitReferences(text)).toEqual([
      'Walters, W. H. (2023). Fabrication and errors in citations. Scientific Reports.',
      B,
    ])
  })

  it('splits a numbered list that is separated by blank lines into groups', () => {
    expect(splitReferences(`1. ${A}\n2. ${B}\n\n3. ${C}`)).toEqual([A, B, C])
  })

  it('splits on an author pattern when the previous line ended the reference', () => {
    expect(splitReferences(`${A}\n${B}\n${C}`)).toEqual([A, B, C])
  })

  it('splits after a URL or DOI that has no final period', () => {
    const a =
      'Walters, W. H. (2023). Title one. Sci Rep. https://doi.org/10.1038/s41598-023-41032-5'
    const b = 'Vaswani, A. (2017). Attention is all you need. NeurIPS.'
    expect(splitReferences(`${a}\n${b}`)).toEqual([a, b])
  })

  it('treats hanging indents as continuation lines', () => {
    const text = `${'Walters, W. H. (2023). A long title that wraps'}\n    Wilder, E. I. continues here. Journal.\n${B}`
    expect(splitReferences(text)).toEqual([
      'Walters, W. H. (2023). A long title that wraps Wilder, E. I. continues here. Journal.',
      B,
    ])
  })

  it('does not split a wrapped line that merely looks like a journal name', () => {
    const text =
      'Walters, W. H. (2023). Fabrication and errors in the citations generated by ChatGPT.\nScientific Reports, 13, 14045.'
    expect(splitReferences(text)).toEqual([
      'Walters, W. H. (2023). Fabrication and errors in the citations generated by ChatGPT. Scientific Reports, 13, 14045.',
    ])
  })

  it('handles corporate authors with a parenthesised year', () => {
    const a =
      'Kementerian Kesehatan RI. (2020). Profil kesehatan Indonesia 2019. Jakarta: Kemenkes RI.'
    const b = 'Badan Pusat Statistik. (2021). Statistik Indonesia 2021. Jakarta: BPS.'
    expect(splitReferences(`${a}\n${b}`)).toEqual([a, b])
  })

  it('handles surnames with particles and hyphens', () => {
    const a = 'van der Berg, J. (2019). Title here. Journal.'
    const b = "O'Brien, K.-L. (2020). Another title. Journal."
    expect(splitReferences(`${a}\n${b}`)).toEqual([a, b])
  })

  it('removes invisible characters, collapses spaces, and normalizes to NFC', () => {
    const messy = 'Wal\u200Bters,   W.\u00A0H. (2023).\tTitle\uFEFF here.'
    expect(splitReferences(messy)).toEqual(['Walters, W. H. (2023). Title here.'])
    expect(splitReferences('Café')).toEqual(['Café'])
  })

  it('accepts Windows and old Mac line endings', () => {
    expect(splitReferences(`${A}\r\n\r\n${B}`)).toEqual([A, B])
    expect(splitReferences(`${A}\r\r${B}`)).toEqual([A, B])
  })

  it('returns one reference for a single block and none for empty input', () => {
    expect(splitReferences(A)).toEqual([A])
    expect(splitReferences('')).toEqual([])
    expect(splitReferences('  \n \n\n ')).toEqual([])
  })

  it('removes bullet markers', () => {
    expect(splitReferences(`- ${A}\n\n- ${B}`)).toEqual([A, B])
  })

  it('does not treat a four-digit year at the start of a line as a list number', () => {
    expect(splitReferences('2023. Some report title without author.')).toEqual([
      '2023. Some report title without author.',
    ])
  })
})

describe('checkLimits', () => {
  const limits = { maxReferences: 3, maxReferenceChars: 50 }

  it('accepts a list within limits', () => {
    expect(checkLimits(['a', 'b', 'c'], limits)).toBeNull()
  })

  it('rejects too many references instead of truncating', () => {
    expect(checkLimits(['a', 'b', 'c', 'd'], limits)).toEqual({
      error: 'too_many_references',
      limit: 3,
      found: 4,
    })
  })

  it('reports the first reference that is too long', () => {
    expect(checkLimits(['ok', 'x'.repeat(51), 'y'.repeat(99)], limits)).toEqual({
      error: 'reference_too_long',
      limit: 50,
      index: 1,
      length: 51,
    })
  })

  it('allows a reference exactly at the limit', () => {
    expect(checkLimits(['x'.repeat(50)], limits)).toBeNull()
  })
})

describe('editing a split list', () => {
  const list = [A, B, C]

  it('merges a reference into the previous one', () => {
    expect(mergeWithPrevious(list, 1)).toEqual([`${A} ${B}`, C])
    expect(mergeWithPrevious(list, 2)).toEqual([A, `${B} ${C}`])
  })

  it('leaves the list alone when there is no previous reference or the index is out of range', () => {
    expect(mergeWithPrevious(list, 0)).toEqual(list)
    expect(mergeWithPrevious(list, 3)).toEqual(list)
    expect(mergeWithPrevious(list, -1)).toEqual(list)
  })

  it('never changes the list it was given', () => {
    const copy = [...list]
    mergeWithPrevious(list, 1)
    replaceReference(list, 1, 'x')
    expect(list).toEqual(copy)
  })

  it('replaces a reference with edited text', () => {
    expect(replaceReference(list, 1, 'Vaswani, A. (2017). Attention is all you need.')).toEqual([
      A,
      'Vaswani, A. (2017). Attention is all you need.',
      C,
    ])
  })

  it('splits one reference into several where the edit has blank lines', () => {
    expect(replaceReference([`${A} ${B}`, C], 0, `${A}\n\n${B}`)).toEqual([A, B, C])
  })

  it('removes a reference whose text was cleared', () => {
    expect(replaceReference(list, 1, '  \n ')).toEqual([A, C])
  })

  it('reads a merge followed by a split as the original list', () => {
    expect(replaceReference(mergeWithPrevious(list, 1), 0, `${A}\n\n${B}`)).toEqual(list)
  })

  it.each([
    ['plain list', list],
    ['one reference', [A]],
    ['empty list', []],
    [
      'references with colons, quotes and brackets',
      [`${A} [Preprint]`, 'Kemenkes RI. (2020). "Pedoman": edisi 2.'],
    ],
  ])('round-trips through joinReferences (%s)', (_name, refs) => {
    expect(splitReferences(joinReferences(refs))).toEqual(refs)
  })

  it('round-trips a list that was first split from numbered lines', () => {
    const refs = splitReferences(`1. ${A}\n2. ${B}\n3. ${C}`)
    expect(refs).toEqual(list)
    expect(splitReferences(joinReferences(refs))).toEqual(refs)
  })
})
