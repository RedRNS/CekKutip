import { describe, expect, it } from 'vitest'
import { apaName, apaReference, initialsOf, joinApaAuthors, withStop } from './apa.js'
import type { MatchedRecord } from './index.js'

const EN_DASH = String.fromCharCode(0x2013)

const record = (over: Partial<MatchedRecord> = {}): MatchedRecord => ({
  source: 'crossref',
  doi: null,
  url: null,
  title: 'A title',
  authors: [],
  authorsFull: [],
  year: 2020,
  venue: null,
  volume: null,
  issue: null,
  pages: null,
  ...over,
})

const WALTERS = record({
  doi: '10.1038/s41598-023-41032-5',
  title: 'Fabrication and errors in the bibliographic citations generated by ChatGPT',
  authors: ['Walters', 'Wilder'],
  authorsFull: ['William H. Walters', 'Esther Isabelle Wilder'],
  year: 2023,
  venue: 'Scientific Reports',
  volume: '13',
  issue: '1',
  pages: '14045',
})

describe('apaReference', () => {
  it('writes a journal article from its record', () => {
    expect(apaReference(WALTERS)).toBe(
      'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13(1), 14045. https://doi.org/10.1038/s41598-023-41032-5',
    )
  })

  it('writes a page range with an en dash', () => {
    expect(apaReference(record({ pages: '10-20', venue: 'J' }))).toBe(
      `A title. (2020). J, 10${EN_DASH}20.`,
    )
  })

  it('writes "n.d." when the record has no year', () => {
    expect(apaReference(record({ year: null, authors: ['Doe'], authorsFull: ['John Doe'] }))).toBe(
      'Doe, J. (n.d.). A title.',
    )
  })

  it('puts the title first when there is no author', () => {
    expect(apaReference(record({ venue: 'Some Journal' }))).toBe('A title. (2020). Some Journal.')
  })

  it('leaves out what the record does not have, and never invents it', () => {
    expect(apaReference(record({ authors: ['Doe'], authorsFull: ['John Doe'] }))).toBe(
      'Doe, J. (2020). A title.',
    )
    expect(apaReference(record({ volume: '7', venue: 'J' }))).toBe('A title. (2020). J, 7.')
    expect(apaReference(record({ issue: '2', venue: 'J' }))).toBe('A title. (2020). J, (2).')
  })

  it('writes a preprint record with no venue as title and link only', () => {
    const r = record({
      source: 'datacite',
      doi: '10.48550/arxiv.1706.03762',
      title: 'Attention Is All You Need',
      authors: ['Vaswani', 'Shazeer'],
      authorsFull: ['Ashish Vaswani', 'Noam Shazeer'],
      year: 2017,
    })
    expect(apaReference(r)).toBe(
      'Vaswani, A., & Shazeer, N. (2017). Attention Is All You Need. https://doi.org/10.48550/arxiv.1706.03762',
    )
  })

  it('links the DOI, or else the record URL, or else nothing', () => {
    expect(apaReference(record({ doi: '10.1/x', url: 'https://example.org' }))).toMatch(
      /https:\/\/doi\.org\/10\.1\/x$/,
    )
    expect(apaReference(record({ url: 'https://example.org/p' }))).toMatch(
      /https:\/\/example\.org\/p$/,
    )
    expect(apaReference(record())).toBe('A title. (2020).')
  })

  it('never links a Garuda page: Garuda is an index of journals, not where the article is published', () => {
    const garuda = record({
      source: 'garuda',
      url: 'https://garuda.kemdiktisaintek.go.id/documents/detail/5105249',
      title: 'Evaluasi kinerja algoritma',
      authors: ['Wantoro'],
      authorsFull: ['Agus Wantoro'],
      year: 2025,
      venue: 'Jurnal Informatika Polinema',
      volume: '11',
      issue: '3',
    })
    expect(apaReference(garuda)).toBe(
      'Wantoro, A. (2025). Evaluasi kinerja algoritma. Jurnal Informatika Polinema, 11(3).',
    )
    // If a Garuda record ever carried a DOI, the DOI is still the right link.
    expect(apaReference({ ...garuda, doi: '10.33795/jip.v11i3.7290' })).toMatch(
      /https:\/\/doi\.org\/10\.33795\/jip\.v11i3\.7290$/,
    )
  })

  it('does not add a second full stop after a title that ends with a question mark', () => {
    expect(apaReference(record({ title: 'Why?', venue: 'J' }))).toBe('Why? (2020). J.')
  })

  it('writes an organisation as it is', () => {
    expect(
      apaReference(
        record({
          authors: ['World Health Organization'],
          authorsFull: ['World Health Organization'],
        }),
      ),
    ).toBe('World Health Organization. (2020). A title.')
  })

  it('falls back to family names when full names are missing', () => {
    expect(apaReference(record({ authors: ['Doe', 'Roe'], authorsFull: undefined }))).toBe(
      'Doe, & Roe. (2020). A title.',
    )
  })

  it('keeps all of up to 20 authors, and shortens 21 or more the APA way', () => {
    const many = (n: number) =>
      record({
        authors: Array.from({ length: n }, (_, i) => `F${String.fromCharCode(65 + i)}`),
        authorsFull: Array.from({ length: n }, (_, i) => `Given F${String.fromCharCode(65 + i)}`),
      })
    expect(apaReference(many(20))).toContain('FS, G., & FT, G. (2020).')
    const long = apaReference(many(21))
    expect(long).toContain('FS, G., . . . FU, G. (2020).')
    expect(long).not.toContain('FT')
  })

  it('is deterministic and does not change the record', () => {
    const copy = JSON.stringify(WALTERS)
    expect(apaReference(WALTERS)).toBe(apaReference(WALTERS))
    expect(JSON.stringify(WALTERS)).toBe(copy)
  })
})

describe('apaName', () => {
  it.each([
    ['William H. Walters', 'Walters', 'Walters, W. H.'],
    ['Ashish Vaswani', 'Vaswani', 'Vaswani, A.'],
    ['Jean-Pierre Dupont', 'Dupont', 'Dupont, J.-P.'],
    ['W. H. Walters', 'Walters', 'Walters, W. H.'],
    ['W.H. Walters', 'Walters', 'Walters, W. H.'],
    ['Ludwig van Beethoven', 'Beethoven', 'van Beethoven, L.'],
    ['M. Lambe L.', 'Lambe L.', 'Lambe L., M.'], // a DataCite creator whose family name has an initial
    ['World Health Organization', 'World Health Organization', 'World Health Organization'],
    ['Cher', 'Cher', 'Cher'],
  ])('%s with family "%s" is written as "%s"', (full, family, expected) => {
    expect(apaName(full, family)).toBe(expected)
  })

  it('uses the family name alone when the full name does not end with it', () => {
    expect(apaName('Zhang Wei', 'Wei Zhang')).toBe('Wei Zhang')
    expect(apaName(undefined, 'Doe')).toBe('Doe')
    expect(apaName('', 'Doe')).toBe('Doe')
  })
})

describe('small helpers', () => {
  it('initialsOf', () => {
    expect(initialsOf('')).toBe('')
    expect(initialsOf('Esther Isabelle')).toBe('E. I.')
    expect(initialsOf('J.R.')).toBe('J. R.')
    expect(initialsOf('Anne-Marie')).toBe('A.-M.')
  })

  it('joinApaAuthors', () => {
    expect(joinApaAuthors([])).toBe('')
    expect(joinApaAuthors(['A'])).toBe('A')
    expect(joinApaAuthors(['A', 'B'])).toBe('A, & B')
    expect(joinApaAuthors(['A', 'B', 'C'])).toBe('A, B, & C')
    expect(joinApaAuthors(['A', 'B'], true)).toBe('A, B, et al.')
  })

  it('withStop', () => {
    expect(withStop('Title')).toBe('Title.')
    expect(withStop('Title.')).toBe('Title.')
    expect(withStop('Why?')).toBe('Why?')
    expect(withStop('Wow!')).toBe('Wow!')
  })
})
