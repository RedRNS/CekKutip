/**
 * Live smoke test: call the real Crossref, OpenAlex, and doi.org through our clients.
 * Usage: npx tsx --env-file=.env scripts/smoke-live.ts     (reads CROSSREF_MAILTO, OPENALEX_API_KEY)
 *        npx tsx scripts/smoke-live.ts                     (public pool, no key)
 * Makes about ten requests. Prints counts and field values, never the contact address.
 */
import { createCrossrefClient } from '../apps/server/src/clients/crossref.js'
import { createDoiClient } from '../apps/server/src/clients/doi.js'
import { createOpenAlexClient } from '../apps/server/src/clients/openalex.js'
import { HttpClient } from '../apps/server/src/lib/http.js'

const mailto = process.env.CROSSREF_MAILTO || undefined
const apiKey = process.env.OPENALEX_API_KEY || undefined
const http = new HttpClient({ userAgent: 'CekKutip-smoke/0.1' })
const crossref = createCrossrefClient({ http, mailto })
const openalex = createOpenAlexClient({ http, apiKey })
const doi = createDoiClient({ http })

console.log(
  `crossref pool: ${mailto ? 'polite (mailto set)' : 'public (no mailto)'}; openalex key: ${apiKey ? 'yes' : 'no'}`,
)

const step = async (label: string, run: () => Promise<unknown>) => {
  const t = Date.now()
  try {
    const result = await run()
    console.log(`ok   ${label} (${Date.now() - t} ms):`, JSON.stringify(result))
  } catch (e) {
    console.log(`FAIL ${label}:`, (e as Error).message)
    process.exitCode = 1
  }
}

const W = 'Fabrication and errors in the bibliographic citations generated by ChatGPT'
await step('crossref by DOI', async () => {
  const r = await crossref.getByDoi('10.1038/s41598-023-41032-5')
  return r.found
    ? { title: r.record.title.slice(0, 40), year: r.record.year, venue: r.record.venue }
    : r
})
await step('crossref unknown DOI', () => crossref.getByDoi('10.9999/this-doi-does-not-exist-12345'))
await step('crossref search', async () =>
  (await crossref.search({ title: W, firstAuthor: 'Walters', year: 2023 })).map((r) => r.doi),
)
await step(
  'crossref search with colon and comma',
  async () =>
    (
      await crossref.search({
        title: 'Errors in Bibliographic Citations: A Continuing Problem, Revisited',
      })
    ).length,
)
await step('doiRA crossref', () => doi.getAgency('10.1038/s41598-023-41032-5'))
await step('doiRA datacite', () => doi.getAgency('10.5281/zenodo.3233821'))
await step('doiRA unknown', () => doi.getAgency('10.9999/this-doi-does-not-exist-12345'))
await step('openalex title search', async () =>
  (await openalex.searchTitle(W)).map((r) => ({ doi: r.doi, year: r.year })),
)
await step(
  'openalex title with comma and colon',
  async () =>
    (
      await openalex.searchTitle(
        'Errors in Bibliographic Citations: A Continuing Problem, Revisited',
      )
    ).length,
)
