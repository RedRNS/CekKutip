/**
 * Post a small reference list to a running server and print one line per result.
 * Usage: npx tsx scripts/smoke-check.ts [baseUrl] [llm|regex]
 * The list mixes real references with invented ones (marked below). It is a smoke test, not the demo list.
 */
import type { StreamEvent } from '@cekkutip/shared'

const base = process.argv[2] ?? 'http://localhost:8787'
const parseMode = process.argv[3] === 'llm' ? 'llm' : 'regex'

const W = 'Fabrication and errors in the bibliographic citations generated by ChatGPT'
const references = [
  // real, correct, no DOI
  `Walters, W. H., & Wilder, E. I. (2023). ${W}. Scientific Reports, 13(1), 14045.`,
  // real, correct, with DOI
  `Walters, W. H., & Wilder, E. I. (2023). ${W}. Scientific Reports, 13(1), 14045. https://doi.org/10.1038/s41598-023-41032-5`,
  // real work, year and journal changed on purpose
  `Walters, W. H., & Wilder, E. I. (2021). ${W}. Nature Communications, 12(1), 100.`,
  // real work, authors changed on purpose
  `Santoso, B., & Wijaya, A. (2023). ${W}. Scientific Reports, 13(1), 14045.`,
  // real DOI attached to an invented, unrelated title
  'Doe, J. (2023). Deep learning methods for rice yield prediction in Central Java. Scientific Reports, 13(1), 14045. https://doi.org/10.1038/s41598-023-41032-5',
  // invented article with a DOI that is not registered
  'Doe, J. (2022). A made-up article about nothing in particular. Journal of Nothing, 1(1), 1-2. https://doi.org/10.9999/this-doi-does-not-exist-12345',
  // invented article, no DOI
  'Wijaya, A. (2020). Dampak Media Sosial Terhadap Prestasi Belajar Mahasiswa Universitas Contoh. Jurnal Contoh Ilmu, 3(2), 10-20.',
  // invented thesis from "Universitas Contoh"
  'Wijaya, A. (2020). Dampak Media Sosial Terhadap Prestasi Belajar Mahasiswa Universitas Contoh [Skripsi, Universitas Contoh]. Repositori Universitas Contoh.',
  // real DataCite DOI (Zenodo)
  'Doe, J. (2019). A dataset about things. Zenodo. https://doi.org/10.5281/zenodo.3233821',
  // real book, widely cited in Indonesian theses
  'Sugiyono. (2017). Metode penelitian kuantitatif, kualitatif, dan R&D. Bandung: Alfabeta.',
  // real conference paper
  'Vaswani, A., Shazeer, N., Parmar, N., Uszkoreit, J., Jones, L., Gomez, A. N., Kaiser, L., & Polosukhin, I. (2017). Attention is all you need. Advances in Neural Information Processing Systems, 30.',
  // real article, well-known
  'He, K., Zhang, X., Ren, S., & Sun, J. (2016). Deep residual learning for image recognition. Proceedings of the IEEE Conference on Computer Vision and Pattern Recognition, 770-778.',
]

const t0 = Date.now()
const res = await fetch(`${base}/api/check`, {
  method: 'POST',
  headers: { 'content-type': 'application/json' },
  body: JSON.stringify({ references, options: { parseMode } }),
})
if (!res.ok || !res.body) {
  console.log('HTTP', res.status, await res.text())
  process.exit(1)
}

const rows: string[] = []
let buffer = ''
const decoder = new TextDecoder()
for await (const chunk of res.body as unknown as AsyncIterable<Uint8Array>) {
  buffer += decoder.decode(chunk, { stream: true })
  let nl: number
  while ((nl = buffer.indexOf('\n')) >= 0) {
    const line = buffer.slice(0, nl)
    buffer = buffer.slice(nl + 1)
    if (line === '') continue
    const e = JSON.parse(line) as StreamEvent
    if (e.type === 'started') console.log(`started: ${e.total} references (${parseMode})`)
    if (e.type === 'result') {
      const r = e.result
      const s = r.scores
      rows[r.index] =
        `${String(r.index + 1).padStart(2)} ${r.status.padEnd(12)} ${r.reasons.join('+').padEnd(34)} ` +
        `t=${s.title.toFixed(2)} a=${s.authors.toFixed(2)} y=${s.yearDiff ?? '-'} v=${s.venue.toFixed(2)} ` +
        `${String(r.latencyMs).padStart(5)}ms ${r.parsed.parseMode.padEnd(5)} ${r.parsed.type.padEnd(16)} | ${r.raw.slice(0, 48)}`
      console.log(`  arrived #${r.index + 1} after ${Date.now() - t0} ms`)
    }
    if (e.type === 'done') {
      console.log(rows.join('\n'))
      console.log('summary:', JSON.stringify(e.summary))
    }
  }
}
console.log(`total ${Date.now() - t0} ms`)
