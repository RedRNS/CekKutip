/**
 * Live check of every server Gemini key (GEMINI_API_KEY, _2, _3) against the real Gemini API.
 * Usage: npx tsx --env-file=.env scripts/smoke-gemini-keys.ts
 * Sends one sample reference to each key and prints whether it worked, is at its limit, or was
 * refused. Never prints a key or Google's error message. Exits with 1 if any key did not work.
 */
import { createGeminiClient } from '../apps/server/src/clients/gemini.js'
import { loadEnv } from '../apps/server/src/config/env.js'
import { ServiceUnavailableError } from '../apps/server/src/lib/http.js'

const env = loadEnv()
const sample =
  'Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13(1), 14045.'

if (env.geminiApiKeys.length === 0) {
  console.log('No Gemini key is set (GEMINI_API_KEY, GEMINI_API_KEY_2, GEMINI_API_KEY_3).')
  process.exit(1)
}
console.log(`model=${env.geminiModel}, ${env.geminiApiKeys.length} key(s)`)

let notOk = 0
for (const [index, apiKey] of env.geminiApiKeys.entries()) {
  const label = `key ${index + 1} of ${env.geminiApiKeys.length}`
  const client = createGeminiClient({
    apiKey,
    model: env.geminiModel,
    temperature: env.geminiTemperature,
    retries: 0,
  })
  try {
    const out = await client.extract([{ i: 0, text: sample }])
    console.log(`${label}: ok (tokens in ${out.usage.inputTokens}, out ${out.usage.outputTokens})`)
  } catch (e) {
    notOk += 1
    if (e instanceof ServiceUnavailableError && e.code === 'rate_limited') {
      console.log(
        `${label}: limit reached (rate_limited). It is used again after the limit resets.`,
      )
    } else if (e instanceof ServiceUnavailableError && e.code === 'blocked') {
      console.log(
        `${label}: refused by Google (blocked). Check that the key is correct and enabled.`,
      )
    } else {
      const code = e instanceof ServiceUnavailableError ? e.code : 'unknown'
      console.log(`${label}: failed (${code}). Try again in a moment.`)
    }
  }
}

console.log(notOk === 0 ? '\nall keys work' : `\n${notOk} key(s) did not work`)
if (notOk > 0) process.exitCode = 1
